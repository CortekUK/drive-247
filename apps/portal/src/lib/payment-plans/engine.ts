/**
 * The operator states money they already received (design §8
 * occurrence_record_payment). Nothing is charged. An outstanding link is
 * released first so the customer cannot pay the same thing twice through it.
 */
export async function recordManualPayment(deps: Pick<EngineDeps, "store" | "notifier">, input: ManualPaymentInput): Promise<{ paymentId: string; attemptId: string; releasedLinks: number }> {
  if (input.asOf) setClock(deps.store, input.asOf);
  if (!Number.isSafeInteger(input.amountCents) || input.amountCents < 1) throw new PlanStoreError("invalid_input", "The amount must be at least 1 cent");
  if (!(MANUAL_METHODS as readonly string[]).includes(input.method)) {
    throw new PlanStoreError("invalid_input", `Method must be one of: ${MANUAL_METHODS.join(", ")}`);
  }
  if (!isISODate(input.paymentDate)) throw new PlanStoreError("invalid_input", `Bad payment date ${input.paymentDate}`);
  const occ = await requireOccurrence(deps.store, input.occurrenceId);
  const plan = await requirePlan(deps.store, occ.planId);
  if (!["scheduled", "due", "failed", "requires_action", "partially_paid"].includes(occ.status)) {
    throw new PlanStoreError("refused", `A ${occ.status} payment cannot take a manual record`);
  }
  const releasedLinks = await releaseOpenLinks(deps.store, occ.id, "Operator recorded a payment by hand");
  const claimed = await deps.store.claim(occ.id, "manual", null);
  if (!isClaimOk(claimed)) {
    throw new PlanStoreError(
      "refused",
      claimed.reason === "nothing_owed"
        ? "The rental owes nothing, so this payment is already covered (it has been marked covered by balance). Record the money as a payment on the rental instead."
        : claimed.reason === "held_elsewhere"
          ? "A card payment is in progress on this payment; wait for it to finish"
          : "This payment cannot take a manual record in its current state",
    );
  }
  try {
    const { paymentId } = await deps.store.recordSuccess({
      attemptId: claimed.claim.attemptId,
      amountCents: input.amountCents,
      providerRef: null,
      providerAccount: null,
      providerMode: null,
      paymentProvider: plan.paymentProvider,
      platformAccount: "uk",
      paymentDate: input.paymentDate,
      method: input.method,
      note: input.note ?? null,
      actorId: input.actorId ?? null,
    });
    return { paymentId, attemptId: claimed.claim.attemptId, releasedLinks };
  } catch (e) {
    try {
      await deps.store.recordFailure({ attemptId: claimed.claim.attemptId, status: "abandoned", errorMessage: `Manual record failed: ${message(e)}` });
    } catch {
      /* recovery abandons a stale manual claim anyway */
    }
    throw e;
  }
}

