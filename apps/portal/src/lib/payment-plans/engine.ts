/**
 * @param linkUrlThisTick the payment URL the due work of THIS tick already
 *   emailed for this occurrence (a link, or a card's fallback link). Reused so
 *   the reminder does not mint a fresh token — which would kill the link in
 *   the email the customer received a moment earlier.
 */
async function sendReminder(deps: EngineDeps, plan: PlanRow, occ: OccurrenceRow, offset: number, linkUrlThisTick?: string): Promise<boolean> {
  const inserted = await deps.store.recordEvent({
    planId: plan.id,
    occurrenceId: occ.id,
    kind: "reminder",
    dedupeKey: `reminder:${occ.id}:${offset}`,
    channel: "email",
    amountCents: remainingOf(occ),
    detail: { offset, dueDate: occ.dueDate, method: occ.collectionMethod },
  });
  if (!inserted) return false;
  // A link that is already out gets a FRESH token in the reminder (only the
  // hash is stored, so the old URL cannot be re-sent). The newest email's
  // link always works; payment-plan-pay tells an old one to use it.
  let url: string | undefined;
  const openLink = (await openAttempts(deps.store, occ.id)).find((a) => a.method === "checkout_link");
  if (openLink && linkUrlThisTick) {
    url = linkUrlThisTick;
  } else if (openLink) {
    const minted = await deps.links.mint(occ.id);
    await deps.store.setLinkToken(occ.id, minted.tokenHash);
    url = minted.url;
  }
  await safeSend(deps, {
    kind: "reminder",
    to: "customer",
    planId: plan.id,
    occurrenceId: occ.id,
    url,
    amountCents: remainingOf(occ),
    dueDate: occ.dueDate,
    detail: { offset, method: occ.collectionMethod },
  });
  return true;
}

async function processDue(deps: EngineDeps, plan: PlanRow, occ: OccurrenceRow, asOf: string): Promise<OccurrenceActionResult> {
  if (plan.status !== "active") return { occurrenceId: occ.id, planId: plan.id, action: "noop" };
  switch (occ.collectionMethod) {
    case "manual": {
      const inserted = await deps.store.recordEvent({
        planId: plan.id,
        occurrenceId: occ.id,
        kind: "occurrence_due",
        dedupeKey: `occurrence_due:${occ.id}`,
        amountCents: remainingOf(occ),
        detail: { dueDate: occ.dueDate },
      });
      if (inserted) {
        await safeSend(deps, { kind: "due_manual", to: "operator", planId: plan.id, occurrenceId: occ.id, amountCents: remainingOf(occ), dueDate: occ.dueDate });
        return { occurrenceId: occ.id, planId: plan.id, action: "due_manual", amountCents: remainingOf(occ) };
      }
      return { occurrenceId: occ.id, planId: plan.id, action: "noop" };
    }
    case "auto_charge":
      if (!(await eligible(deps.store, occ, asOf))) return { occurrenceId: occ.id, planId: plan.id, action: "not_eligible" };
      return chargeOccurrence(deps, plan, occ, asOf);
    case "checkout_link":
      if (!(await eligible(deps.store, occ, asOf))) return { occurrenceId: occ.id, planId: plan.id, action: "not_eligible" };
      return sendLink(deps, plan, occ, asOf);
    default:
      throw new PlanStoreError("invalid_input", `Unknown collection method ${String(occ.collectionMethod)}`);
  }
}

/** One pass of the engine. See the file header for the order and why. */
export async function runTick(deps: EngineDeps, opts: { asOf: string; tenantId?: string; planId?: string }): Promise<TickResult> {
  const asOf = new Date(opts.asOf).toISOString();
  setClock(deps.store, asOf);
  const filter = { tenantId: opts.tenantId, planId: opts.planId };
  const result: TickResult = { asOf, recovered: [], reminders: [], actions: [], errors: [] };
  const plans = new Map<string, PlanRow>();
  const planOf = async (id: string) => {
    let p = plans.get(id);
    if (!p) {
      p = await requirePlan(deps.store, id);
      plans.set(id, p);
    }
    return p;
  };

  // 1. Recovery first: an in-flight charge must be resolved before anything
  //    else touches its occurrence.
  let stale: AttemptRow[] = [];
  try {
    stale = await deps.store.staleAttempts(STALE_ATTEMPT_SECONDS, asOf);
  } catch (e) {
    result.errors.push({ stage: "recovery", message: message(e) });
  }
  for (const att of stale) {
    try {
      const r = await recoverAttempt(deps, att, asOf, filter);
      if (r) result.recovered.push(r);
    } catch (e) {
      result.errors.push({ stage: "recovery", attemptId: att.id, occurrenceId: att.occurrenceId, message: message(e) });
    }
  }

  // 1b. Renewals: reconcile, append, post, insure — before any reminder quotes
  //     a period's price and before the due work can charge one.
  if (storeHasRenewals(deps.store)) {
    const stage = await runRenewalStage({ store: deps.store, notifier: deps.notifier, insurer: deps.insurer ?? null }, asOf, filter);
    result.renewals = stage;
    for (const e of stage.errors) result.errors.push({ stage: "renewals", occurrenceId: e.occurrenceId, message: e.planId ? `plan ${e.planId}: ${e.message}` : e.message });
  }

  // One reminder pass. `which` picks the offsets: ≤ 0 before the due work,
  // > 0 after it. Each pass lists what is open AT THAT MOMENT, so the second
  // one never reminds about an occurrence the due work has just settled.
  const remind = async (which: "before_due" | "after_due", planOfPass: (id: string) => Promise<PlanRow>, linkUrls: Map<string, string>) => {
    let forReminders: OccurrenceRow[] = [];
    try {
      forReminders = await deps.store.listForReminders(asOf, REMINDER_HORIZON_DAYS, filter);
    } catch (e) {
      result.errors.push({ stage: "reminders", message: message(e) });
    }
    for (const occ of forReminders) {
      try {
        if (occ.status === "processing") continue; // a card charge is running right now
        const plan = await planOfPass(occ.planId);
        if (plan.status !== "active") continue;
        const today = localDateInZone(asOf, plan.timezone);
        // A card retry still to come TODAY decides whether "still unpaid" is
        // true. The cron ticks all day, so without this the first tick after
        // local midnight would send it hours before a 10:00 retry succeeds.
        // The retry's own tick (later today) sends it if the retry fails.
        const retryLaterToday =
          which === "after_due" &&
          occ.status === "failed" &&
          !!occ.nextAttemptAt &&
          compareInstants(occ.nextAttemptAt, asOf) > 0 &&
          localDateInZone(occ.nextAttemptAt, plan.timezone) === today;
        for (const offset of plan.reminderOffsets ?? []) {
          if (which === "before_due" ? offset > 0 : offset <= 0) continue;
          if (retryLaterToday) continue;
          if (addDays(occ.dueDate, offset) !== today) continue;
          const sent = await sendReminder(deps, plan, occ, offset, linkUrls.get(occ.id));
          result.reminders.push({ occurrenceId: occ.id, planId: plan.id, offset, sent });
        }
      } catch (e) {
        result.errors.push({ stage: "reminders", occurrenceId: occ.id, message: message(e) });
      }
    }
  };

  // 2. Reminders that come before the money: "due in two days", "charging today".
  await remind("before_due", planOf, new Map());

  // 3. Due work.
  let due: OccurrenceRow[] = [];
  try {
    due = await deps.store.collectDue(asOf, filter);
  } catch (e) {
    result.errors.push({ stage: "due", message: message(e) });
  }
  for (const occ of due) {
    try {
      // Re-read: recovery or a reminder earlier in this tick may have moved it.
      const fresh = await requireOccurrence(deps.store, occ.id);
      const plan = await requirePlan(deps.store, fresh.planId); // fresh: a pause earlier in the tick must stop this
      result.actions.push(await processDue(deps, plan, fresh, asOf));
    } catch (e) {
      result.errors.push({ stage: "due", occurrenceId: occ.id, message: message(e) });
    }
  }

  // 4. Reminders that say "still unpaid" — only now, after this tick's retry
  //    has had its chance, and only for what it left open. A plan the due
  //    work touched is re-read: it may have paused it (an integration bug),
  //    and a paused plan sends no reminders.
  for (const occ of due) plans.delete(occ.planId);
  const linkUrls = new Map<string, string>();
  for (const a of result.actions) {
    const url = a.url ?? a.fallback?.url;
    if (url) linkUrls.set(a.occurrenceId, url);
  }
  await remind("after_due", planOf, linkUrls);
  return result;
}

