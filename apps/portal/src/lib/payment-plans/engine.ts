/**
 * Auto-collection eligibility (design §6 / D12), as the engine applies it.
 *
 *   failed         — only when next_attempt_at has arrived.
 *   due / partially_paid — only when no CARD or LINK attempt has ever been made
 *                    on it, other than ones `abandoned` before reaching anyone.
 *
 * This is D12's "attempt_no = 0" with two refinements the scenarios require:
 * a MANUAL record does not count (S10: 5000 recorded by hand the day before,
 * the card is still charged the 15000 remainder on the due date), and an
 * attempt recovery abandoned because it was never sent does not count (the
 * occurrence is still owed and nothing ever asked the card). A refunded card
 * or link payment DOES count — its succeeded attempt stays on the row — so a
 * refunded occurrence is never charged again automatically (S14).
 */
export function isAutoEligible(occ: OccurrenceRow, attempts: AttemptRow[], asOf: string): boolean {
  if (occ.status === "failed") return !!occ.nextAttemptAt && compareInstants(occ.nextAttemptAt, asOf) <= 0;
  if (occ.status !== "due" && occ.status !== "partially_paid") return false;
  if (compareInstants(occ.dueAt, asOf) > 0) return false;
  if (occ.attemptNo === 0) return true;
  return attempts.every((a) => a.method === "manual" || a.status === "abandoned");
}

async function eligible(store: EngineStore, occ: OccurrenceRow, asOf: string): Promise<boolean> {
  if (occ.status === "failed" || occ.attemptNo === 0) return isAutoEligible(occ, [], asOf);
  return isAutoEligible(occ, await store.listAttempts({ occurrenceId: occ.id }), asOf);
}

