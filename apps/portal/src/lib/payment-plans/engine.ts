/**
 * Claim a checkout_link attempt, mint the stable /pay/plan/<token> URL, store
 * its hash, email it. The attempt stays in flight until the webhook records
 * the payment (onLinkPaid) or an operator releases it.
 */
async function sendLink(deps: EngineDeps, plan: PlanRow, occ: OccurrenceRow, asOf: string, opts: { fallbackReason?: string } = {}): Promise<OccurrenceActionResult> {
  if (opts.fallbackReason !== undefined) {
    await deps.store.recordEvent({ planId: plan.id, occurrenceId: occ.id, kind: "fallback_to_link", detail: { reason: opts.fallbackReason } });
  }
  const claimed = await deps.store.claim(occ.id, "checkout_link", deps.provider.account);
  if (!isClaimOk(claimed)) {
    return { occurrenceId: occ.id, planId: plan.id, action: claimed.reason === "nothing_owed" ? "covered_by_balance" : claimed.reason };
  }
  const c = claimed.claim;
  await deps.store.markInFlight(c.attemptId);
  let url: string;
  try {
    const minted = await deps.links.mint(occ.id);
    await deps.store.setLinkToken(occ.id, minted.tokenHash);
    url = minted.url;
  } catch (e) {
    // No usable link exists: release the claim so the occurrence is not held
    // by an attempt nobody can pay.
    try {
      await deps.store.recordFailure({ attemptId: c.attemptId, status: "abandoned", errorMessage: `Link could not be created: ${message(e)}` });
    } catch {
      /* reported below */
    }
    throw e;
  }
  const sendError = await safeSend(deps, {
    kind: "link",
    to: "customer",
    planId: plan.id,
    occurrenceId: occ.id,
    url,
    amountCents: c.amountCents,
    dueDate: occ.dueDate,
    detail: { attemptId: c.attemptId, ...(opts.fallbackReason ? { reason: opts.fallbackReason } : {}) },
  });
  // The store does not write link_sent (pp_set_link_token has no event): the
  // engine writes it once the link has actually gone out. Never the URL — it
  // carries the token, which is a bearer credential for this payment.
  await deps.store.recordEvent({
    planId: plan.id,
    occurrenceId: occ.id,
    kind: "link_sent",
    channel: "email",
    amountCents: c.amountCents,
    detail: { attemptId: c.attemptId, ...(sendError ? { deliveryError: sendError } : {}) },
  });
  return { occurrenceId: occ.id, planId: plan.id, action: "link_sent", attemptId: c.attemptId, attemptNo: c.attemptNo, idempotencyKey: c.idempotencyKey, amountCents: c.amountCents, url };
}

async function openAttempts(store: EngineStore, occurrenceId: string): Promise<AttemptRow[]> {
  return (await store.listAttempts({ occurrenceId })).filter((a) => OPEN_ATTEMPT.has(a.status));
}

/**
 * Release (abandon) any outstanding LINK attempt on an occurrence, so an
 * operator action — a manual record, a card retry, a skip, a plan change — can
 * proceed. Refuses (PlanStoreError 'attempt_in_flight') when a CARD charge is
 * in flight: that one must finish or be recovered, never be abandoned.
 * Returns how many links were released.
 */
export async function releaseOpenLinks(store: EngineStore, occurrenceId: string, reason: string): Promise<number> {
  const open = await openAttempts(store, occurrenceId);
  if (open.some((a) => a.method !== "checkout_link")) {
    throw new PlanStoreError("attempt_in_flight", "A card payment is in progress on this occurrence; wait for it to finish");
  }
  for (const a of open) await store.recordFailure({ attemptId: a.id, status: "abandoned", errorMessage: reason });
  return open.length;
}

/** releaseOpenLinks over every occurrence of a plan (before an update or a cancel). */
export async function releasePlanLinks(store: EngineStore, planId: string, reason: string): Promise<number> {
  let n = 0;
  for (const occ of await store.listOccurrences(planId)) n += await releaseOpenLinks(store, occ.id, reason);
  return n;
}

