/** Record a card success; if the record cannot be written, give the money back (design §7 compensation). */
async function recordCardSuccess(deps: EngineDeps, ctx: AttemptCtx, providerRef: string, amountCents: number, asOf: string): Promise<OccurrenceActionResult> {
  const { plan, occ } = ctx;
  const base: OccurrenceActionResult = {
    occurrenceId: occ.id,
    planId: plan.id,
    action: "charged",
    attemptId: ctx.attemptId,
    attemptNo: ctx.attemptNo,
    idempotencyKey: ctx.idempotencyKey,
    amountCents,
    providerRef,
    chargeClass: "succeeded",
  };
  try {
    const { paymentId } = await deps.store.recordSuccess({
      attemptId: ctx.attemptId,
      amountCents,
      providerRef,
      providerAccount: deps.provider.account,
      providerMode: deps.provider.mode,
      paymentProvider: plan.paymentProvider,
      platformAccount: deps.provider.platformAccount ?? "uk",
      paymentDate: localDateInZone(asOf, plan.timezone),
      method: "Card",
    });
    return { ...base, paymentId };
  } catch (recordErr) {
    // The card WAS charged and the payment row could not be written. Leaving
    // it would be money taken with nothing on the ledger; retrying could take
    // it twice. So: refund it (keyed, so a repeat of this path cannot refund
    // twice), then say so. Precedent: auto-extend-rentals' rollback, which
    // pauses rather than retrying whenever the refund itself fails.
    const why = message(recordErr);
    let refund: { ok: boolean; message?: string };
    try {
      refund = await deps.provider.refund(providerRef, amountCents, `pp-refund:${ctx.attemptId}`);
    } catch (e) {
      refund = { ok: false, message: message(e) };
    }
    if (refund.ok) {
      try {
        await deps.store.recordFailure({
          attemptId: ctx.attemptId,
          status: "failed",
          providerRef,
          errorCode: "record_failed_refunded",
          errorMessage: `Charged, but the payment could not be recorded (${why}); refunded in full.`,
          nextAttemptAt: null,
        });
        await deps.store.recordEvent({
          planId: plan.id,
          occurrenceId: occ.id,
          kind: "charge_failed",
          amountCents,
          detail: { attemptId: ctx.attemptId, compensated: "refunded", providerRef, error: why },
        });
      } catch (e2) {
        // The store is still failing. The attempt stays in flight; recovery
        // will replay the key, see the charge, look it up NET of the refund,
        // find nothing, and fail it — no phantom payment. Pause if we can.
        await pauseAndAlert(deps, plan, occ, "refunded_unrecorded", `Charge ${providerRef} was refunded after the payment could not be recorded, and the failure could not be written either: ${message(e2)}`);
      }
      await safeSend(deps, {
        kind: "alert",
        to: "operator",
        planId: plan.id,
        occurrenceId: occ.id,
        amountCents,
        detail: { problem: "charge_refunded_after_record_failure", providerRef, attemptId: ctx.attemptId, error: why },
      });
      return { ...base, action: "failed", paymentId: undefined, reason: "The payment could not be recorded and was refunded." };
    }
    // Refund failed: money is out and unrecorded. Mark indeterminate (recovery
    // records it once the store is healthy — the money is real), PAUSE the
    // plan so nothing else is charged, and alert a human.
    try {
      await deps.store.recordFailure({
        attemptId: ctx.attemptId,
        status: "indeterminate",
        providerRef,
        errorCode: "record_failed_refund_failed",
        errorMessage: `Charged, the payment could not be recorded (${why}), and the refund failed (${refund.message ?? "unknown"}).`,
      });
    } catch {
      /* the attempt is still in flight either way; recovery sees it */
    }
    await pauseAndAlert(deps, plan, occ, "refund_failed", `Charge ${providerRef} could not be recorded (${why}) and its refund failed (${refund.message ?? "unknown"}). Money is captured and unrecorded.`);
    return { ...base, action: "indeterminate", paymentId: undefined, reason: "Charged but not recorded; refund failed — plan paused for review." };
  }
}

async function pauseAndAlert(deps: Pick<EngineDeps, "store" | "notifier">, plan: PlanRow, occ: OccurrenceRow | null, problem: string, detailText: string): Promise<void> {
  let paused = false;
  try {
    const fresh = await deps.store.getPlan(plan.id);
    if (fresh?.status === "active") {
      await deps.store.pausePlan(plan.id, null, `${problem}: ${detailText}`.slice(0, 500));
      paused = true;
    }
  } catch {
    paused = false;
  }
  await safeSend(deps, {
    kind: "alert",
    to: "operator",
    planId: plan.id,
    occurrenceId: occ?.id,
    detail: { problem, message: detailText, planPaused: paused },
  });
}

/** Turn a provider answer into state. Shared by the first call and by recovery's replay. */
async function applyOutcome(deps: EngineDeps, ctx: AttemptCtx, outcome: ChargeOutcome, asOf: string): Promise<OccurrenceActionResult> {
  const { plan, occ } = ctx;
  const cls = classifyCharge(outcome);
  const base: OccurrenceActionResult = {
    occurrenceId: occ.id,
    planId: plan.id,
    action: "failed",
    attemptId: ctx.attemptId,
    attemptNo: ctx.attemptNo,
    idempotencyKey: ctx.idempotencyKey,
    amountCents: ctx.amountCents,
    chargeClass: cls,
  };

  if (outcome.kind === "succeeded") return recordCardSuccess(deps, ctx, outcome.providerRef, ctx.amountCents, asOf);

  if (outcome.kind === "indeterminate") {
    // Money may or may not have moved. Keep the claim (occurrence stays
    // processing) and let recovery replay THIS key — never a new one.
    await deps.store.recordFailure({ attemptId: ctx.attemptId, status: "indeterminate", errorMessage: outcome.message ?? "No definitive answer from the provider" });
    return { ...base, action: "indeterminate" };
  }

  if (outcome.kind === "in_use") {
    // 409: another request holds this key right now. Leave the attempt in
    // flight; recovery picks it up after the lease.
    return { ...base, action: "in_use" };
  }

  // Declined.
  const reason = customerSafeReason(outcome.declineCode, outcome.errorCode);
  const failure = {
    attemptId: ctx.attemptId,
    providerRef: outcome.providerRef,
    declineCode: outcome.declineCode,
    errorCode: outcome.errorCode,
    errorMessage: outcome.message ?? null,
  };
  const operatorNote = (extra: Record<string, unknown>) =>
    safeSend(deps, {
      kind: "failed",
      to: "operator",
      planId: plan.id,
      occurrenceId: occ.id,
      amountCents: ctx.amountCents,
      dueDate: occ.dueDate,
      detail: { attemptId: ctx.attemptId, attemptNo: ctx.attemptNo, chargeClass: cls, reason, ...extra },
    });

  if (cls === "integration_bug") {
    await deps.store.recordFailure({ ...failure, status: "failed", nextAttemptAt: null });
    await deps.store.recordEvent({ planId: plan.id, occurrenceId: occ.id, kind: "charge_failed", amountCents: ctx.amountCents, detail: { attemptId: ctx.attemptId, chargeClass: cls, errorCode: outcome.errorCode, declineCode: outcome.declineCode } });
    // Our mistake, not the customer's: never email them; stop the plan until a human looks.
    await pauseAndAlert(deps, plan, occ, "integration_bug", `Charge refused with ${outcome.errorCode ?? outcome.declineCode ?? "an unknown code"}: ${outcome.message ?? ""}`.trim());
    return { ...base, action: "paused_integration", reason, providerRef: outcome.providerRef };
  }

  if (cls === "needs_customer") {
    await deps.store.recordFailure({ ...failure, status: "requires_action" });
    await deps.store.recordEvent({ planId: plan.id, occurrenceId: occ.id, kind: "requires_action", amountCents: ctx.amountCents, detail: { attemptId: ctx.attemptId, declineCode: outcome.declineCode, errorCode: outcome.errorCode } });
    await operatorNote({});
    const result: OccurrenceActionResult = { ...base, action: "requires_action", reason, providerRef: outcome.providerRef };
    return withFallback(deps, result, plan, occ.id, asOf, reason);
  }

  const retryable = cls === "retry_later" || cls === "transient";
  const canRetry = retryable && ctx.attemptNo < plan.maxAttempts;
  let nextAttemptAt: string | null = null;
  if (canRetry) {
    nextAttemptAt =
      cls === "retry_later"
        ? // The local calendar decides: "in 2 days at 10:00" is 10:00 local on
          // that day, not +48 h (which drifts an hour across a DST change).
          dueAtUtc(addDays(localDateInZone(asOf, plan.timezone), plan.retryAfterDays), plan.chargeLocalTime, plan.timezone)
        : addHoursToInstant(asOf, TRANSIENT_RETRY_HOURS);
  }
  await deps.store.recordFailure({ ...failure, status: "failed", nextAttemptAt });
  await deps.store.recordEvent({
    planId: plan.id,
    occurrenceId: occ.id,
    kind: "charge_failed",
    amountCents: ctx.amountCents,
    detail: { attemptId: ctx.attemptId, chargeClass: cls, declineCode: outcome.declineCode, errorCode: outcome.errorCode, nextAttemptAt },
  });
  await operatorNote({ nextAttemptAt });
  if (canRetry) return { ...base, action: "retry_scheduled", reason, nextAttemptAt, providerRef: outcome.providerRef };
  return withFallback(deps, { ...base, action: "failed", reason, nextAttemptAt: null, providerRef: outcome.providerRef }, plan, occ.id, asOf, reason);
}

/** D7: when the card needs the customer or is dead, send them a link — or, with fallback off, tell them. */
async function withFallback(deps: EngineDeps, result: OccurrenceActionResult, plan: PlanRow, occurrenceId: string, asOf: string, reason: string): Promise<OccurrenceActionResult> {
  const occ = await requireOccurrence(deps.store, occurrenceId);
  if (plan.fallbackToLink) {
    const fallback = await sendLink(deps, plan, occ, asOf, { fallbackReason: reason });
    return { ...result, fallback };
  }
  await safeSend(deps, {
    kind: "failed",
    to: "customer",
    planId: plan.id,
    occurrenceId: occ.id,
    amountCents: remainingOf(occ),
    dueDate: occ.dueDate,
    detail: { reason },
  });
  return result;
}

/** Claim → mark in flight → charge with the claim's key → apply the outcome. */
async function chargeOccurrence(deps: EngineDeps, plan: PlanRow, occ: OccurrenceRow, asOf: string): Promise<OccurrenceActionResult> {
  const claimed = await deps.store.claim(occ.id, "auto_charge", deps.provider.account);
  if (!isClaimOk(claimed)) {
    return { occurrenceId: occ.id, planId: plan.id, action: claimed.reason === "nothing_owed" ? "covered_by_balance" : claimed.reason };
  }
  const c: ClaimOk = claimed.claim;
  // Write-ahead: the attempt says "in flight" BEFORE the provider is called, so
  // a worker that dies mid-call leaves a row recovery will replay, never a
  // `claimed` row it would abandon while money moved.
  await deps.store.markInFlight(c.attemptId);
  await deps.store.recordEvent({
    planId: plan.id,
    occurrenceId: occ.id,
    kind: "charge_attempted",
    dedupeKey: `charge_attempted:${c.attemptId}`,
    amountCents: c.amountCents,
    detail: { attemptId: c.attemptId, attemptNo: c.attemptNo, idempotencyKey: c.idempotencyKey },
  });
  const ctx: AttemptCtx = { plan, occ, attemptId: c.attemptId, attemptNo: c.attemptNo, amountCents: c.amountCents, idempotencyKey: c.idempotencyKey };
  let outcome: ChargeOutcome;
  try {
    outcome = await deps.provider.charge(chargeRequest(plan, occ, { id: c.attemptId, amountCents: c.amountCents, idempotencyKey: c.idempotencyKey }, deps.provider.account));
  } catch (e) {
    // A thrown provider call is an unknown outcome, exactly like a 5xx.
    outcome = { kind: "indeterminate", message: message(e) };
  }
  return applyOutcome(deps, ctx, outcome, asOf);
}

