const OPERATOR_COLLECTABLE = new Set(["due", "failed", "requires_action", "partially_paid"]);

/**
 * The operator's "Retry" (design §8 occurrence_retry): collect THIS occurrence
 * now, by its method, through the same path the cron takes — but without the
 * automatic-eligibility gate, because a person decided. This is the only way a
 * refunded occurrence (D12) is ever charged again.
 */
export async function collectOccurrenceNow(deps: EngineDeps, occurrenceId: string, asOf: string): Promise<OccurrenceActionResult> {
  setClock(deps.store, asOf);
  const occ = await requireOccurrence(deps.store, occurrenceId);
  const plan = await requirePlan(deps.store, occ.planId);
  if (plan.status !== "active") throw new PlanStoreError("refused", `The plan is ${plan.status}; resume it before collecting`);
  if (!OPERATOR_COLLECTABLE.has(occ.status)) {
    throw new PlanStoreError("refused", occ.status === "scheduled" ? "This payment is not due yet — move its date to collect it now" : `A ${occ.status} payment cannot be collected`);
  }
  switch (occ.collectionMethod) {
    case "manual":
      throw new PlanStoreError("refused", "This payment is collected by hand — record the payment instead");
    case "checkout_link":
      return sendOccurrenceLink(deps, occurrenceId, asOf);
    case "auto_charge": {
      await releaseOpenLinks(deps.store, occ.id, "Operator retried the card");
      const fresh = await requireOccurrence(deps.store, occ.id);
      return chargeOccurrence(deps, plan, fresh, asOf);
    }
    default:
      throw new PlanStoreError("invalid_input", `Unknown collection method ${String(occ.collectionMethod)}`);
  }
}

/**
 * The operator's "Send link" (design §8 occurrence_send_link). When a link is
 * already out, re-sends it with a fresh token (the old URL stops working);
 * otherwise claims a new link attempt.
 */
export async function sendOccurrenceLink(deps: EngineDeps, occurrenceId: string, asOf: string): Promise<OccurrenceActionResult> {
  setClock(deps.store, asOf);
  const occ = await requireOccurrence(deps.store, occurrenceId);
  const plan = await requirePlan(deps.store, occ.planId);
  // pp_claim only collects on an active plan; a re-send follows the same rule.
  if (plan.status !== "active") throw new PlanStoreError("refused", `The plan is ${plan.status}; resume it before sending a link`);
  if (!OPERATOR_COLLECTABLE.has(occ.status)) {
    throw new PlanStoreError("refused", occ.status === "scheduled" ? "This payment is not due yet — move its date to send a link now" : `A ${occ.status} payment cannot be sent a link`);
  }
  const open = await openAttempts(deps.store, occ.id);
  if (open.some((a) => a.method !== "checkout_link")) {
    throw new PlanStoreError("attempt_in_flight", "A card payment is in progress on this occurrence; wait for it to finish");
  }
  const existing = open.find((a) => a.method === "checkout_link");
  if (existing) {
    const minted = await deps.links.mint(occ.id);
    await deps.store.setLinkToken(occ.id, minted.tokenHash);
    const sendError = await safeSend(deps, { kind: "link", to: "customer", planId: plan.id, occurrenceId: occ.id, url: minted.url, amountCents: remainingOf(occ), dueDate: occ.dueDate, detail: { attemptId: existing.id, resent: true } });
    await deps.store.recordEvent({
      planId: plan.id,
      occurrenceId: occ.id,
      kind: "link_sent",
      channel: "email",
      amountCents: remainingOf(occ),
      detail: { attemptId: existing.id, resent: true, ...(sendError ? { deliveryError: sendError } : {}) },
    });
    return { occurrenceId: occ.id, planId: plan.id, action: "link_sent", attemptId: existing.id, attemptNo: existing.attemptNo, idempotencyKey: existing.idempotencyKey, amountCents: existing.amountCents, url: minted.url };
  }
  return sendLink(deps, plan, occ, asOf);
}

export interface LinkPaidInput {
  attemptId: string;
  providerRef: string;
  amountCents: number;
  paidAt: string;
  checkoutSessionId?: string | null;
  /** pm_… saved by the Checkout (setup_future_usage); becomes the plan's card. */
  paymentMethodRef?: string | null;
  providerMode?: "test" | "live" | null;
  platformAccount?: "uk" | "uae";
}

export type LinkPaidResult =
  | { status: "recorded"; paymentId: string; occurrenceStatusBefore: string }
  | { status: "already_recorded"; paymentId: string | null }
  | { status: "duplicate_payment"; paymentId: string | null };

/**
 * What the webhook does when a plan's Checkout completes (design §8). The
 * store call is idempotent on the attempt, so a double delivery writes one
 * payment (S7). A DIFFERENT payment for an attempt that already succeeded —
 * the customer paid two sessions — is not silently dropped: it is reported to
 * the operator, who decides whether to refund it.
 */
export async function onLinkPaid(deps: Pick<EngineDeps, "store" | "notifier">, input: LinkPaidInput): Promise<LinkPaidResult> {
  setClock(deps.store, input.paidAt);
  const att = await deps.store.getAttempt(input.attemptId);
  if (!att) throw new PlanStoreError("not_found", `Attempt ${input.attemptId} not found`);
  const occ = await requireOccurrence(deps.store, att.occurrenceId);
  const plan = await requirePlan(deps.store, occ.planId);

  if (att.status === "succeeded") {
    if (!input.providerRef || !att.providerRef || att.providerRef === input.providerRef) {
      return { status: "already_recorded", paymentId: att.paymentId };
    }
    await safeSend(deps, {
      kind: "alert",
      to: "operator",
      planId: plan.id,
      occurrenceId: occ.id,
      amountCents: input.amountCents,
      detail: { problem: "duplicate_link_payment", attemptId: att.id, recordedRef: att.providerRef, extraRef: input.providerRef, checkoutSessionId: input.checkoutSessionId ?? null },
    });
    return { status: "duplicate_payment", paymentId: att.paymentId };
  }

  const before = occ.status;
  const { paymentId } = await deps.store.recordSuccess({
    attemptId: att.id,
    amountCents: input.amountCents,
    providerRef: input.providerRef,
    providerAccount: att.providerAccount,
    providerMode: input.providerMode ?? att.providerMode ?? null,
    paymentProvider: plan.paymentProvider,
    platformAccount: input.platformAccount ?? "uk",
    paymentDate: localDateInZone(input.paidAt, plan.timezone),
    method: "Card",
    checkoutSessionId: input.checkoutSessionId ?? null,
  });
  if (input.paymentMethodRef && input.paymentMethodRef !== plan.stripePaymentMethodId) {
    await deps.store.setPaymentMethod(plan.id, input.paymentMethodRef);
  }
  if (before === "paid" || before === "skipped" || before === "superseded" || before === "cancelled" || before === "waived") {
    // Paid through a link after the occurrence was already settled or closed
    // (released link, operator recorded cash meanwhile). The money is real and
    // is now on the rental; a person should decide about a refund.
    await safeSend(deps, {
      kind: "alert",
      to: "operator",
      planId: plan.id,
      occurrenceId: occ.id,
      amountCents: input.amountCents,
      detail: { problem: "link_paid_after_settled", occurrenceStatus: before, paymentId, providerRef: input.providerRef },
    });
  }
  return { status: "recorded", paymentId, occurrenceStatusBefore: before };
}

