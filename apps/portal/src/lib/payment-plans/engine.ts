/** pp:{account or 'platform'}:{occurrence}:{attempt_no} — design §4. The store builds it at claim; this is the same rule for display and checks. */
export function idempotencyKey(account: string | null, occurrenceId: string, attemptNo: number): string {
  return `pp:${account ?? "platform"}:${occurrenceId}:${attemptNo}`;
}

function setClock(store: unknown, asOf: string): void {
  const s = store as { setNow?: (asOf: string) => void };
  if (typeof s?.setNow === "function") s.setNow(asOf);
}

const message = (e: unknown): string => (e instanceof Error ? e.message : String(e));

/**
 * Narrow a ClaimResult. A type predicate rather than `if (!c.ok)`, because the
 * portal compiles these files with strictNullChecks off, where TypeScript does
 * not narrow a union on a boolean-literal discriminant.
 */
export function isClaimOk(c: ClaimResult): c is { ok: true; claim: ClaimOk } {
  return c.ok === true;
}

function remainingOf(occ: OccurrenceRow): number {
  return Math.max(0, occ.amountCents - occ.amountPaidCents);
}

/** Never let a notification failure break a money path; report it instead. */
async function safeSend(deps: { notifier: Notifier }, n: Notification): Promise<string | null> {
  try {
    await deps.notifier.send(n);
    return null;
  } catch (e) {
    return message(e);
  }
}

async function requirePlan(store: EngineStore | (PlanStore & PlanLookups), planId: string): Promise<PlanRow> {
  const plan = await store.getPlan(planId);
  if (!plan) throw new PlanStoreError("not_found", `Plan ${planId} not found`);
  return plan;
}

async function requireOccurrence(store: PlanLookups, occurrenceId: string): Promise<OccurrenceRow> {
  const occ = await store.getOccurrence(occurrenceId);
  if (!occ) throw new PlanStoreError("not_found", `Occurrence ${occurrenceId} not found`);
  return occ;
}

