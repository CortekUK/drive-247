/**
 * The provider holds a charge for this attempt, but not for the amount that
 * was claimed (someone refunded part of it at Stripe). pp_record_success
 * records a card attempt at exactly its claimed amount, so neither "record it"
 * nor "fail it" is true. Leave the attempt where it is, pause the plan, and
 * hand it to a person.
 */
async function partialRefundFound(
  deps: EngineDeps,
  plan: PlanRow,
  occ: OccurrenceRow,
  att: AttemptRow,
  found: { providerRef: string; amountCents: number },
  path: "replayed" | "looked_up",
): Promise<RecoveryResult> {
  if (att.status !== "indeterminate") {
    await deps.store.recordFailure({ attemptId: att.id, status: "indeterminate", providerRef: found.providerRef, errorCode: "amount_mismatch", errorMessage: `Provider holds ${found.amountCents} cents net; ${att.amountCents} were claimed` });
  }
  await pauseAndAlert(deps, plan, occ, "recovery_amount_mismatch", `Attempt ${att.id}: charge ${found.providerRef} holds ${found.amountCents} cents net of refunds, but ${att.amountCents} were claimed. Reconcile by hand.`);
  return { attemptId: att.id, occurrenceId: occ.id, path, outcome: "amount_mismatch" };
}

async function recoverAttempt(deps: EngineDeps, att: AttemptRow, asOf: string, filter: { tenantId?: string; planId?: string }): Promise<RecoveryResult | null> {
  const occ = await requireOccurrence(deps.store, att.occurrenceId);
  if (filter.tenantId && occ.tenantId !== filter.tenantId) return null;
  if (filter.planId && occ.planId !== filter.planId) return null;
  const plan = await requirePlan(deps.store, occ.planId);
  const base = { attemptId: att.id, occurrenceId: occ.id };

  if (att.method === "manual" || att.status === "claimed") {
    // Never reached a provider (claimed = markInFlight never ran; manual has
    // no provider). Nothing can have moved.
    await deps.store.recordFailure({ attemptId: att.id, status: "abandoned", errorMessage: "Claimed but never sent; released by recovery" });
    return { ...base, path: "abandoned_unsent", outcome: "abandoned" };
  }

  if ((att.providerAccount ?? null) !== (deps.provider.account ?? null)) {
    // Replaying on a different account would be a different charge.
    throw new Error(`Attempt ${att.id} ran on ${att.providerAccount ?? "the platform"}, not ${deps.provider.account ?? "the platform"}; not recovered here`);
  }

  const ctx: AttemptCtx = { plan, occ, attemptId: att.id, attemptNo: att.attemptNo, amountCents: att.amountCents, idempotencyKey: att.idempotencyKey };
  const age = att.createdAt ? secondsBetween(att.createdAt, asOf) : Number.POSITIVE_INFINITY;

  if (plan.status === "active" && age < REPLAY_WINDOW_SECONDS) {
    let outcome: ChargeOutcome;
    try {
      outcome = await deps.provider.charge(chargeRequest(plan, occ, { id: att.id, amountCents: att.amountCents, idempotencyKey: att.idempotencyKey }, att.providerAccount));
    } catch (e) {
      outcome = { kind: "indeterminate", message: message(e) };
    }
    if (outcome.kind === "succeeded") {
      // A replay returns Stripe's CACHED first answer, which does not know
      // about a refund made since (the compensation path refunds). Confirm the
      // money is still there before writing a payment for it.
      const found = await deps.provider.findByAttempt(att.id);
      if (!found) {
        await deps.store.recordFailure({ attemptId: att.id, status: "failed", providerRef: outcome.providerRef, errorCode: "charge_refunded_or_missing", errorMessage: "Replay reported success but no un-refunded charge exists", nextAttemptAt: null });
        await pauseAndAlert(deps, plan, occ, "recovery_mismatch", `Attempt ${att.id}: the provider replayed a success (${outcome.providerRef}) but no un-refunded charge was found.`);
        return { ...base, path: "replayed", outcome: "refunded_or_missing" };
      }
      if (found.amountCents !== att.amountCents) {
        return partialRefundFound(deps, plan, occ, att, found, "replayed");
      }
      const r = await recordCardSuccess(deps, ctx, found.providerRef, att.amountCents, asOf);
      return { ...base, path: "replayed", outcome: r.action, paymentId: r.paymentId };
    }
    if (outcome.kind === "indeterminate") {
      if (att.status !== "indeterminate") {
        await deps.store.recordFailure({ attemptId: att.id, status: "indeterminate", errorMessage: outcome.message ?? "No definitive answer on replay" });
      }
      return { ...base, path: "replayed", outcome: "indeterminate" };
    }
    const r = await applyOutcome(deps, ctx, outcome, asOf);
    return { ...base, path: "replayed", outcome: r.action, paymentId: r.paymentId };
  }

  // Too old to replay safely (Stripe forgets keys after 24 h, and a forgotten
  // key is a NEW charge), or the plan is no longer active: look it up.
  const found = await deps.provider.findByAttempt(att.id);
  if (found && found.amountCents !== att.amountCents) {
    return partialRefundFound(deps, plan, occ, att, found, "looked_up");
  }
  if (found) {
    try {
      const { paymentId } = await deps.store.recordSuccess({
        attemptId: att.id,
        amountCents: att.amountCents,
        providerRef: found.providerRef,
        providerAccount: att.providerAccount,
        providerMode: deps.provider.mode,
        paymentProvider: plan.paymentProvider,
        platformAccount: deps.provider.platformAccount ?? "uk",
        paymentDate: localDateInZone(asOf, plan.timezone),
        method: "Card",
      });
      return { ...base, path: "looked_up", outcome: "charged", paymentId };
    } catch (e) {
      // The money is real; the attempt stays in flight and the next tick
      // tries again. Say so loudly — no refund here, the customer owes it.
      await safeSend(deps, { kind: "alert", to: "operator", planId: plan.id, occurrenceId: occ.id, detail: { problem: "recovered_charge_unrecorded", attemptId: att.id, providerRef: found.providerRef, error: message(e) } });
      throw e;
    }
  }
  await deps.store.recordFailure({ attemptId: att.id, status: "abandoned", errorMessage: "No charge found at the provider for this attempt" });
  return { ...base, path: "looked_up", outcome: "abandoned" };
}

