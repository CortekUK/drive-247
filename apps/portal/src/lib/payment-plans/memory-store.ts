  /** pp__insert_occurrences: at least one draft; seqs follow the plan's current maximum, in draft seq order. */
  private insertOccurrences(plan: PlanState, drafts: OccurrenceDraft[]): number {
    if (!Array.isArray(drafts) || drafts.length === 0) throw new PlanStoreError("invalid_input", "payment plan: at least one occurrence is required");
    for (const d of drafts) {
      if (!isISODate(d.dueDate)) throw new PlanStoreError("invalid_input", "occurrence draft: dueDate is required");
      if (!Number.isSafeInteger(d.amountCents) || d.amountCents < 1) {
        throw new PlanStoreError("invalid_input", `occurrence draft #${d.seq}: amount must be ≥ 1 cent`);
      }
      if (plan.extendsRental && (!d.periodStart || !d.periodEnd)) {
        throw new PlanStoreError("invalid_input", "occurrence draft: a renewal period needs periodStart and periodEnd");
      }
    }
    // Validate every due_at before writing, so a bad zone/time leaves nothing behind.
    const dueAts = drafts.map((d) => dueAtUtc(d.dueDate, plan.chargeLocalTime, plan.timezone));
    const base = this.occsOf(plan.id).reduce((m, o) => Math.max(m, o.seq), 0);
    const ordered = drafts.map((d, i) => ({ d, i })).sort((a, b) => (a.d.seq ?? a.i + 1) - (b.d.seq ?? b.i + 1) || a.i - b.i);
    ordered.forEach(({ d, i }, n) => {
      const id = this.nextId("occ");
      this.occurrences.set(id, {
        id,
        planId: plan.id,
        tenantId: plan.tenantId,
        rentalId: plan.rentalId,
        seq: base + n + 1,
        planVersion: plan.version,
        dueDate: d.dueDate,
        dueAt: dueAts[i],
        periodStart: d.periodStart ?? null,
        periodEnd: d.periodEnd ?? null,
        amountCents: d.amountCents,
        amountPaidCents: 0,
        collectionMethod: plan.collectionMethod,
        status: "scheduled",
        attemptNo: 0,
        nextAttemptAt: null,
        linkTokenHash: null,
        movedFrom: null,
        paidAt: null,
        note: null,
        createdAt: this.clock,
        updatedAt: this.clock,
        renews: plan.extendsRental,
        extensionId: null,
        insuranceStatus: null,
      });
    });
    return drafts.length;
  }

