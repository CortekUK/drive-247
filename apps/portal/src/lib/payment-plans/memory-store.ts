  /** pp_append_renewal_period. */
  async appendRenewalPeriod(planId: string, draft: OccurrenceDraft, _actorId?: string | null): Promise<{ occurrenceId: string; appended: boolean }> {
    if (!draft || !isISODate(draft.periodStart) || !isISODate(draft.periodEnd) || !isISODate(draft.dueDate) || compareDates(draft.periodEnd, draft.periodStart) <= 0) {
      throw new PlanStoreError("invalid_input", "pp_append_renewal_period: a period needs dueDate and periodStart < periodEnd");
    }
    if (draft.days !== undefined && draft.days !== diffDays(draft.periodStart, draft.periodEnd)) {
      throw new PlanStoreError("invalid_input", `pp_append_renewal_period: days ${draft.days} disagrees with the period`);
    }
    if (!Number.isSafeInteger(draft.amountCents) || draft.amountCents < 1) throw new PlanStoreError("invalid_input", "pp_append_renewal_period: amount must be at least 1 cent");
    const plan = this.requirePlan(planId);
    if (plan.status !== "active") throw new PlanStoreError("refused", `pp_append_renewal_period: plan ${planId} is ${plan.status}`);
    const live = this.occsOf(planId).filter((o) => o.renews && o.status !== "superseded" && o.status !== "cancelled");
    const existing = live.find((o) => o.periodStart === draft.periodStart);
    if (existing) return Promise.resolve({ occurrenceId: existing.id, appended: false });
    const rental = this.requireRental(plan.rentalId);
    let chain: ISODate | null = rental.endDate;
    for (const o of live) if (o.periodEnd && (!chain || compareDates(o.periodEnd, chain) > 0)) chain = o.periodEnd;
    if (!chain || chain !== draft.periodStart) {
      throw new PlanStoreError("invalid_input", `pp_append_renewal_period: the next period starts on ${chain} (the rental's end, or the last period's end), not ${draft.periodStart}`);
    }
    const dueAt = dueAtUtc(draft.dueDate, plan.chargeLocalTime, plan.timezone);
    const id = this.nextId("occ");
    const seq = this.occsOf(planId).reduce((m, o) => Math.max(m, o.seq), 0) + 1;
    this.occurrences.set(id, {
      id,
      planId,
      tenantId: plan.tenantId,
      rentalId: plan.rentalId,
      seq,
      planVersion: plan.version,
      dueDate: draft.dueDate,
      dueAt,
      periodStart: draft.periodStart,
      periodEnd: draft.periodEnd,
      amountCents: draft.amountCents,
      amountPaidCents: 0,
      collectionMethod: plan.collectionMethod,
      status: "scheduled",
      attemptNo: 0,
      nextAttemptAt: null,
      linkTokenHash: null,
      movedFrom: null,
      paidAt: null,
      note: null,
      createdAt: this.clock,
      updatedAt: this.clock,
      renews: true,
      extensionId: null,
      insuranceStatus: null,
    });
    if (plan.rule.end.kind === "open" && compareDates(draft.dueDate, plan.rule.end.through) > 0) {
      plan.rule = { ...plan.rule, end: { kind: "open", through: draft.dueDate } };
      plan.updatedAt = this.clock;
    }
    return Promise.resolve({ occurrenceId: id, appended: true });
  }

  /** pp_post_renewal_period. */
