    const b = input.breakdown;
    const cents = [b?.rentalCents, b?.taxCents, b?.serviceFeeCents, b?.totalCents];
    if (!b || cents.some((x) => !Number.isSafeInteger(x) || (x as number) < 0) || b.totalCents !== b.rentalCents + b.taxCents + b.serviceFeeCents || b.totalCents < 1) {
      throw new PlanStoreError("invalid_input", `pp_post_renewal_period: breakdown must be whole cents ≥ 0 whose total (≥ 1) is their sum (got ${JSON.stringify(b)})`);
    }
    const occ = this.requireOcc(input.occurrenceId);
    if (!occ.renews) throw new PlanStoreError("invalid_input", `pp_post_renewal_period: occurrence ${occ.id} is not a renewal period`);
