  private requireExt(id: string): MemoryExtension {
    const e = this.extensions.get(id);
    if (!e) throw new PlanStoreError("not_found", `rental_extension ${id} not found`);
    return e;
  }

  /** pp_extension_owed_cents. */
  private extOwed(ext: MemoryExtension): number {
    return ext.charges.reduce((s, c) => s + c.remainingCents, 0);
  }

  /** pp__extension_applied_cents: money applied to its charges (payment_applications). */
  private extApplied(ext: MemoryExtension): number {
    return ext.charges.reduce((s, c) => s + c.appliedCents, 0);
  }

  /** The rental's open extension charges in the live FIFO's order: category priority, then due date, then posting order. */
  private openExtCharges(rentalId: string): MemoryCharge[] {
    const out: MemoryCharge[] = [];
    const exts = [...this.extensions.values()].filter((e) => e.rentalId === rentalId).sort((a, b) => a.sequenceNumber - b.sequenceNumber);
    for (const e of exts) for (const c of e.charges) if (c.remainingCents > 0) out.push(c);
    return out.sort((a, b) => EXT_PRIORITY[a.category] - EXT_PRIORITY[b.category] || compareDates(a.dueDate, b.dueDate));
  }

  /** Apply up to `limit` cents of the rental's unapplied credit (owedCents < 0) to its open extension charges. */
  private applyCredit(rental: MemoryRental, limit = Number.POSITIVE_INFINITY): void {
    let credit = Math.min(Math.max(0, -rental.owedCents), limit);
    for (const c of this.openExtCharges(rental.id)) {
      if (credit <= 0) break;
      const take = Math.min(c.remainingCents, credit);
      c.remainingCents -= take;
      c.appliedCents += take;
      credit -= take;
      rental.owedCents += take;
    }
  }

  /**
   * A captured payment with no extension and no target categories: the live
   * FIFO pays the rental's base charges first and whatever is left of THIS
   * payment reaches open extension charges. Older unapplied credit is not
   * touched here (pp_apply_rental_credit, at claim time, does that).
   */
  private applyGeneralPayment(rental: MemoryRental, cents: number): void {
    const creditBefore = Math.max(0, -rental.owedCents);
    rental.owedCents -= cents;
    const leftoverOfThisPayment = Math.max(0, -rental.owedCents) - creditBefore;
    if (leftoverOfThisPayment > 0) this.applyCredit(rental, leftoverOfThisPayment);
  }

  /** A payment carrying extension_id + the Extension* targets: this extension's charges only. Returns what was applied. */
  private applyToExtension(ext: MemoryExtension, cents: number): number {
    let left = cents;
    const charges = [...ext.charges].sort((a, b) => EXT_PRIORITY[a.category] - EXT_PRIORITY[b.category]);
    for (const c of charges) {
      if (left <= 0) break;
      const take = Math.min(c.remainingCents, left);
      c.remainingCents -= take;
      c.appliedCents += take;
      left -= take;
    }
    return cents - left;
  }

  /** pp__extend_rental_end — finalize_rental_extension's rental half: forward only. */
  private extendRentalEnd(rental: MemoryRental, previousEnd: ISODate, newEnd: ISODate): boolean {
    if (newEnd && (!rental.endDate || compareDates(newEnd, rental.endDate) > 0)) {
      rental.endDate = newEnd;
      rental.previousEndDate = rental.previousEndDate ?? previousEnd;
      rental.originalEndDate = rental.originalEndDate ?? previousEnd;
      return true;
    }
    return false;
  }

  /** pp__settle_renewal_period: settle from the ledger; when paid, finalize the extension (no payment row) and say so. */
  private settleRenewal(occ: OccState, via: string): OccurrenceStatus {
    this.settle(occ);
    if (!occ.extensionId) throw new PlanStoreError("invalid_input", `pp__settle_renewal_period: occurrence ${occ.id} is not a posted renewal period`);
    if (occ.status === "paid") {
      const ext = this.requireExt(occ.extensionId);
      const rental = this.requireRental(occ.rentalId);
      if (ext.status !== "refunded") ext.status = "paid";
      ext.paidAt = ext.paidAt ?? this.clock;
      ext.paidAmountCents = Math.max(ext.paidAmountCents, this.extApplied(ext));
      const moved = this.extendRentalEnd(rental, ext.previousEndDate, ext.newEndDate);
      this.pushEvent({
        planId: occ.planId,
        occurrenceId: occ.id,
        kind: "rental_extended",
        dedupeKey: `rental_extended:${occ.id}`,
        detail: { extensionId: ext.id, via, endDateMoved: moved, endDate: rental.endDate },
      });
    }
    return occ.status;
  }

