  /** pp_collect_due. */
  async collectDue(asOf: string, filter?: { tenantId?: string; planId?: string }): Promise<OccurrenceRow[]> {
    const out: OccState[] = [];
    for (const plan of this.plans.values()) {
      if (plan.status !== "active") continue;
      if (filter?.tenantId && plan.tenantId !== filter.tenantId) continue;
      if (filter?.planId && plan.id !== filter.planId) continue;
      for (const occ of this.occsOf(plan.id)) {
        const dueNow = compareInstants(occ.dueAt, asOf) <= 0;
        if (occ.status === "scheduled" && dueNow) this.setStatus(occ, "due");
        if ((occ.status === "due" || occ.status === "partially_paid") && dueNow) out.push(occ);
        else if (occ.status === "failed" && occ.nextAttemptAt && compareInstants(occ.nextAttemptAt, asOf) <= 0) out.push(occ);
      }
    }
    out.sort((a, b) => compareInstants(a.dueAt, b.dueAt) || a.seq - b.seq);
    return Promise.resolve(out.map((o) => this.toOccRow(o)));
  }

