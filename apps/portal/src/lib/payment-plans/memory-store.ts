  /** pp_list_for_reminders: open, not processing, due_date within ±horizon of the plan-local today. */
  async listForReminders(asOf: string, horizonDays: number, filter?: { tenantId?: string; planId?: string }): Promise<OccurrenceRow[]> {
    const out: OccState[] = [];
    const h = Math.max(0, horizonDays);
    for (const plan of this.plans.values()) {
      if (plan.status !== "active") continue;
      if (filter?.tenantId && plan.tenantId !== filter.tenantId) continue;
      if (filter?.planId && plan.id !== filter.planId) continue;
      const today = localDateInZone(asOf, plan.timezone);
      const lo = addDays(today, -h);
      const hi = addDays(today, h);
      for (const o of this.occsOf(plan.id)) {
        if (!OPEN.includes(o.status)) continue;
        if (o.dueDate < lo || o.dueDate > hi) continue;
        out.push(o);
      }
    }
    out.sort((a, b) => compareInstants(a.dueAt, b.dueAt) || a.seq - b.seq);
    return Promise.resolve(out.map((o) => this.toOccRow(o)));
  }

  /** pp_rental_owed_cents: every open charge (extensions' included) less unapplied credit, floor 0. */
  private owed(rentalId: string): number {
    const rental = this.requireRental(rentalId);
    let ext = 0;
    for (const e of this.extensions.values()) if (e.rentalId === rentalId) ext += this.extOwed(e);
    return Math.max(0, rental.owedCents + ext);
  }

