/**
 * Payment plans — WHEN: a ScheduleRule → due dates → periods → drafts.
 *
 * The semantics are types.ts's `ScheduleRule` / `AmountSpec` comments and
 * docs/PAYMENT_PLANS_DESIGN.md §3; the golden table there (§3.1) is the
 * acceptance test and was derived by hand, not from this file.
 *
 * Three rules this file exists to keep, because each one is a real way a
 * schedule silently moves money to a day nobody chose:
 *
 *   1. Every date is computed from the ANCHOR, never from the previous
 *      occurrence. Occurrence N of a monthly-on-the-31st plan is
 *      "anchor month + N·interval, clamped", so one February cannot turn every
 *      later payment into the 28th (design D4).
 *   2. Weeks are ISO weeks (Monday start, WKST=MO). "Every 2 weeks on Tue and
 *      Sun" means both days of every other Monday-to-Sunday week — the Sunday
 *      belongs to the week that STARTED on the Monday before it.
 *   3. Nothing here touches an instant. Dates are calendar strings; due_at is
 *      derived later, once, from (date, charge time, IANA zone) in dates.ts.
 *
 * Canonical copy: supabase/functions/_shared/payment-plans/. The portal copy is
 * generated by scripts/sync-payment-plans.mjs — edit here, then sync.
 */

import type { AmountSpec, ISODate, OccurrenceDraft, ScheduleOverride, ScheduleRule, Weekday } from "./types.ts";
import { MAX_OCCURRENCES } from "./types.ts";
import { PlanRuleError } from "./errors.ts";
import { addDays, compareDates, diffDays, isoWeekday, mondayOf, monthlyDate, parseISODate } from "./dates.ts";
import { computeAmounts } from "./amounts.ts";

export { PlanRuleError } from "./errors.ts";

/** Interval ceiling — the `interval_count` CHECK on payment_plans is 1..52. */
export const MAX_INTERVAL = 52;

/** A rule with its optional parts checked and normalised (weekdays sorted, dates de-duplicated). */
export interface NormalizedRule extends ScheduleRule {
  byWeekday?: Weekday[];
  dates?: ISODate[];
}

/** The generated dates of a rule, before amounts. */
export interface ExpandedSchedule {
  /** Due dates in order, the stub (if any) first. */
  dates: ISODate[];
  /** True when dates[0] is the on_anchor stub (not produced by the rhythm itself). */
  hasStub: boolean;
  /**
   * Where the LAST occurrence's period ends (exclusive): the rental end for
   * end kind 'rental_end', otherwise the date the rhythm would produce next.
   * For freq 'dates' — which has no rhythm to continue — the next listed date
   * beyond the end if there is one, else the day after the last date (the
   * payment covers its own day).
   */
  lastPeriodEnd: ISODate;
}

/** One occurrence's period, before amounts: [periodStart, periodEnd). */
export interface Period {
  periodStart: ISODate;
  periodEnd: ISODate;
  days: number;
}

function assertInteger(value: unknown, what: string): asserts value is number {
  if (typeof value !== "number" || !Number.isInteger(value)) {
    throw new RangeError(`${what} must be an integer, got ${JSON.stringify(value)}`);
  }
}

/**
 * Check a rule and return a normalised copy. Throws PlanRuleError for every
 * mistake an operator can make in the form (design §3), RangeError for
 * malformed input no form can produce.
 */
export function validateRule(rule: ScheduleRule): NormalizedRule {
  if (!rule || typeof rule !== "object") throw new RangeError("A schedule rule is required");
  parseISODate(rule.anchor);

  if (typeof rule.interval !== "number" || !Number.isInteger(rule.interval) || rule.interval < 1 || rule.interval > MAX_INTERVAL) {
    throw new PlanRuleError("interval_invalid", `Interval must be a whole number from 1 to ${MAX_INTERVAL}`);
  }
  if (rule.firstOccurrence !== "on_anchor" && rule.firstOccurrence !== "on_rhythm") {
    throw new RangeError(`firstOccurrence must be 'on_anchor' or 'on_rhythm', got ${JSON.stringify(rule.firstOccurrence)}`);
  }

  const out: NormalizedRule = { ...rule };

  switch (rule.freq) {
    case "daily":
      break;
    case "weekly": {
      const days = Array.isArray(rule.byWeekday) ? rule.byWeekday : [];
      if (days.length === 0 || days.some((d) => !Number.isInteger(d) || d < 1 || d > 7)) {
        throw new PlanRuleError("weekday_required", "Pick at least one weekday (Monday = 1 … Sunday = 7)");
      }
      out.byWeekday = [...new Set(days)].sort((a, b) => a - b) as Weekday[];
      break;
    }
    case "monthly": {
      const d = rule.byMonthDay;
      if (typeof d !== "number" || !Number.isInteger(d) || !(d === -1 || (d >= 1 && d <= 31))) {
        throw new PlanRuleError("month_day_invalid", "Day of month must be 1–31, or the last day of the month");
      }
      break;
    }
    case "dates": {
      const list = Array.isArray(rule.dates) ? rule.dates : [];
      if (list.length === 0) throw new PlanRuleError("dates_required", "Pick at least one date");
      for (const d of list) parseISODate(d);
      const sorted = [...new Set(list)].sort(compareDates);
      if (compareDates(sorted[0], rule.anchor) < 0) {
        throw new PlanRuleError("date_before_anchor", `${sorted[0]} is before the plan starts (${rule.anchor})`);
      }
      out.dates = sorted;
      break;
    }
    default:
      throw new RangeError(`Unknown freq ${JSON.stringify((rule as { freq?: unknown }).freq)}`);
  }

  const end = rule.end;
  if (!end || typeof end !== "object") throw new RangeError("A schedule end is required");
  switch (end.kind) {
    case "rental_end":
      parseISODate(end.rentalEnd);
      break;
    case "count":
      if (typeof end.count !== "number" || !Number.isInteger(end.count) || end.count < 1) {
        throw new PlanRuleError("count_invalid", "The number of payments must be at least 1");
      }
      if (end.count > MAX_OCCURRENCES) {
        throw new PlanRuleError("too_many_occurrences", `A plan can have at most ${MAX_OCCURRENCES} payments`);
      }
      break;
    case "until":
      parseISODate(end.until);
      break;
    case "open":
      parseISODate(end.through);
      break;
    default:
      throw new RangeError(`Unknown end kind ${JSON.stringify((end as { kind?: unknown }).kind)}`);
  }
  return out;
}

/**
 * The rhythm's own dates, ascending, all ≥ anchor. Infinite for daily/weekly/
 * monthly (the caller stops it), finite for 'dates'. Never includes the stub.
 */
function* rhythm(rule: NormalizedRule): Generator<ISODate> {
  const anchor = rule.anchor;
  switch (rule.freq) {
    case "daily": {
      for (let k = 0; ; k++) yield addDays(anchor, k * rule.interval);
    }
    case "weekly": {
      const monday = mondayOf(anchor);
      const days = rule.byWeekday!;
      for (let w = 0; ; w += rule.interval) {
        const weekStart = addDays(monday, 7 * w);
        for (const wd of days) {
          const date = addDays(weekStart, wd - 1);
          if (compareDates(date, anchor) >= 0) yield date;
        }
      }
    }
    case "monthly": {
      const { y, m } = parseISODate(anchor);
      for (let k = 0; ; k += rule.interval) {
        const date = monthlyDate(y, m, k, rule.byMonthDay!);
        if (compareDates(date, anchor) >= 0) yield date;
      }
    }
    case "dates": {
      for (const date of rule.dates!) yield date;
      return;
    }
  }
}

/** Does `date` fall inside the schedule's end? (count is handled by the caller.) */
function withinEnd(rule: NormalizedRule, date: ISODate): boolean {
  const end = rule.end;
  switch (end.kind) {
    case "rental_end":
      return compareDates(date, end.rentalEnd) < 0; // strictly before the return date
    case "until":
      return compareDates(date, end.until) <= 0; // on or before
    case "open":
      return compareDates(date, end.through) <= 0; // on or before
    case "count":
      return true;
  }
}

/**
 * Expand a rule into its due dates, the stub, and where the last period ends.
 * Throws no_occurrences when nothing survives the end, too_many_occurrences
 * past MAX_OCCURRENCES.
 */
export function expandRule(input: ScheduleRule): ExpandedSchedule {
  const rule = validateRule(input);
  const it = rhythm(rule);
  const dates: ISODate[] = [];
  const cap = rule.end.kind === "count" ? rule.end.count : MAX_OCCURRENCES;

  // The first rhythm date decides whether a stub is needed.
  let pending = it.next();
  let hasStub = false;
  if (rule.firstOccurrence === "on_anchor" && rule.freq !== "dates") {
    const first = pending.done ? null : pending.value;
    if (first !== rule.anchor) hasStub = true;
  }

  // `nextAfter` ends up as the first date the rhythm produced that did NOT
  // make the list — the natural end of the last period.
  let nextAfter: ISODate | null = null;
  const push = (date: ISODate): boolean => {
    if (!withinEnd(rule, date)) {
      nextAfter = date;
      return false;
    }
    if (dates.length >= cap) {
      if (rule.end.kind === "count") {
        nextAfter = date;
        return false;
      }
      throw new PlanRuleError("too_many_occurrences", `This rule produces more than ${MAX_OCCURRENCES} payments`);
    }
    dates.push(date);
    return true;
  };

  let open = true;
  if (hasStub) open = push(rule.anchor);
  // A stub that fails the end (until < anchor) leaves the list empty, and an
  // empty list throws below — so the loop need not run in that case.
  while (open && !pending.done) {
    open = push(pending.value);
    pending = it.next();
  }
  // Leaving the loop with `open` still true means a finite 'dates' list ran
  // out inside the end: nextAfter stays null and the day-after rule applies.

  if (dates.length === 0) {
    throw new PlanRuleError("no_occurrences", "This rule produces no payment dates before it ends");
  }

  const last = dates[dates.length - 1];
  let lastPeriodEnd: ISODate;
  if (rule.end.kind === "rental_end") {
    lastPeriodEnd = rule.end.rentalEnd;
  } else if (nextAfter !== null) {
    lastPeriodEnd = nextAfter;
  } else {
    // Only reachable for freq 'dates' whose list ended inside the end.
    lastPeriodEnd = addDays(last, 1);
  }
  return { dates, hasStub, lastPeriodEnd };
}

/** Just the due dates, stub included, in order. */
export function generateDates(rule: ScheduleRule): ISODate[] {
  return expandRule(rule).dates;
}

/**
 * The period each occurrence covers: [start_i, start_{i+1}) with start_1 = the
 * ANCHOR and start_i = occurrence i's own (original) due date for i > 1; the
 * last ends at `lastPeriodEnd`. So the first payment always starts at the
 * anchor and no rental day is ever left unbilled (types.ts AmountSpec).
 */
export function computePeriods(anchor: ISODate, expanded: ExpandedSchedule): Period[] {
  const { dates, lastPeriodEnd } = expanded;
  return dates.map((date, i) => {
    const periodStart = i === 0 ? anchor : date;
    const periodEnd = i + 1 < dates.length ? dates[i + 1] : lastPeriodEnd;
    return { periodStart, periodEnd, days: diffDays(periodStart, periodEnd) };
  });
}

/**
 * Rule + amount (+ due-date moves chosen in the preview) → the drafts that
 * pp_create_plan / pp_replace_future store.
 *
 * Overrides move a DUE DATE only; the period and amount stay what the rule
 * made them ("moved to Monday, still covers Oct 2–8").
 */
export function buildSchedule(rule: ScheduleRule, amount: AmountSpec, overrides?: ScheduleOverride[]): OccurrenceDraft[] {
  const expanded = expandRule(rule);
  const periods = computePeriods(rule.anchor, expanded);
  const amounts = computeAmounts(amount, periods.map((p) => p.days));

  const drafts: OccurrenceDraft[] = expanded.dates.map((dueDate, i) => ({
    seq: i + 1,
    dueDate,
    periodStart: periods[i].periodStart,
    periodEnd: periods[i].periodEnd,
    days: periods[i].days,
    amountCents: amounts[i],
    isStub: expanded.hasStub && i === 0,
  }));

  for (const o of overrides ?? []) {
    assertInteger(o?.seq, "Override seq");
    const draft = drafts.find((d) => d.seq === o.seq);
    if (!draft) throw new RangeError(`Override names occurrence #${o.seq}, which this rule does not produce`);
    parseISODate(o.moveTo);
    if (compareDates(o.moveTo, rule.anchor) < 0) {
      throw new PlanRuleError("date_before_anchor", `Payment #${o.seq} cannot move to ${o.moveTo}, before the plan starts`);
    }
    draft.dueDate = o.moveTo;
  }
  return drafts;
}

