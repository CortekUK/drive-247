export interface Assertion {
  label: string;
  expected: unknown;
  actual: unknown;
  pass: boolean;
}

export interface ScenarioRun {
  id: string;
  title: string;
  assertions: Assertion[];
  pass: boolean;
  /** ticks, events, attempts, keys, payments, provider calls — see ScenarioEvidence. */
  evidence: unknown;
}

export interface ScenarioRental {
  rentalId: string;
  tenantId: string;
  customerId: string;
}

/** A payments row on the rental, as the scenarios read it (both stores). */
export interface ScenarioPayment {
  id: string;
  occurrenceId: string | null;
  amountCents: number;
  refundCents: number;
  method: string;
  providerRef: string | null;
}

export type ScenarioStore = PlanStore & PlanOperations & PlanLookups & LedgerFixture;

export interface ScenarioContext {
  store: ScenarioStore;
  provider: SimulatedProvider;
  notifier: RecordingNotifier;
  links: SimulatedLinkMinter;
  /** One engine pass (runTick) at this instant; resolves to its TickResult. */
  tick(asOf: string): Promise<unknown>;
  // ── Additive to the pinned API: what a script needs from a context. The UI
  // never builds a context itself (createMemoryContext does), so these are
  // free to require.
  /** 'memory' | 'pglite' — for evidence. */
  kind: string;
  /** A rental owing `owedCents` (one charge) for the scenario to plan against. */
  seedRental(owedCents: number): Promise<ScenarioRental>;
  /** Move the store's clock (an operator action at an instant, no engine pass). */
  at(asOf: string): Promise<void>;
  /** The rental's payments rows. */
  payments(rentalId: string): Promise<ScenarioPayment[]>;
  /** payment_plan_revisions rows for a plan. */
  revisionCount(planId: string): Promise<number>;
}

export interface Scenario {
  id: string;
  title: string;
  why: string;
  run(ctx: ScenarioContext): Promise<ScenarioRun>;
}

export interface ScenarioEvidence {
  context: string;
  error: string | null;
  ticks: TickResult[];
  notes: Record<string, unknown>;
  plan: PlanRow | null;
  occurrences: OccurrenceRow[];
  attempts: AttemptRow[];
  keys: string[];
  events: (PlanEvent & { id: string; createdAt: string })[];
  payments: ScenarioPayment[];
  providerCalls: { key: string; amountCents: number; occurrenceId: string | null; attemptId: string | null }[];
  charges: { idempotencyKey: string; providerRef: string; amountCents: number; occurrenceId: string; refundedCents: number }[];
  refunds: { providerRef: string; amountCents: number }[];
  notifications: unknown[];
  links: unknown[];
}

