const TZ = "America/New_York";
/** Before any scenario time; plans are created "now". */
const SETUP_AT = "2026-09-25T12:00:00.000Z";

export const BASE_RULE: ScheduleRule = {
  freq: "weekly",
  interval: 1,
  byWeekday: [5],
  anchor: "2026-10-02",
  firstOccurrence: "on_anchor",
  end: { kind: "count", count: 3 },
};
export const BASE_AMOUNT: AmountSpec = { mode: "split_total", totalCents: 60000 };
/** 10:00 America/New_York in EDT = 14:00Z. */
export const BASE_DUE_AT = ["2026-10-02T14:00:00.000Z", "2026-10-09T14:00:00.000Z", "2026-10-16T14:00:00.000Z"] as const;

interface Setup {
  planId: string;
  rental: ScenarioRental;
  occ: OccurrenceRow[];
  ids: string[];
}

async function setup(
  ctx: ScenarioContext,
  r: Rec,
  opts: { owedCents?: number; rule?: ScheduleRule; amount?: AmountSpec; method?: CollectionMethod; checkBase?: boolean } = {},
): Promise<Setup> {
  await ctx.at(SETUP_AT);
  const rental = await ctx.seedRental(opts.owedCents ?? 60000);
  const rule = opts.rule ?? BASE_RULE;
  const amount = opts.amount ?? BASE_AMOUNT;
  const plan: Omit<PlanRow, "id" | "version" | "status"> = {
    tenantId: rental.tenantId,
    rentalId: rental.rentalId,
    customerId: rental.customerId,
    rule,
    amount,
    currency: "usd",
    timezone: TZ,
    chargeLocalTime: "10:00",
    collectionMethod: opts.method ?? "auto_charge",
    fallbackToLink: true,
    maxAttempts: 3,
    retryAfterDays: 2,
    reminderOffsets: [-2, 0, 2],
    paymentProvider: "stripe",
    stripePaymentMethodId: "pm_sim_card",
    extendsRental: false,
  };
  const planId = await ctx.store.createPlan({ plan, occurrences: buildSchedule(rule, amount) });
  r.planId = planId;
  r.rentalId = rental.rentalId;
  const occ = await ctx.store.listOccurrences(planId);
  if (opts.checkBase !== false) {
    r.check(
      "base plan: 10-02, 10-09, 10-16 × 20000, due 10:00 New York = 14:00Z",
      [
        ["2026-10-02", BASE_DUE_AT[0], 20000],
        ["2026-10-09", BASE_DUE_AT[1], 20000],
        ["2026-10-16", BASE_DUE_AT[2], 20000],
      ],
      occ.map((o) => [o.dueDate, o.dueAt, o.amountCents]),
    );
  }
  return { planId, rental, occ, ids: occ.map((o) => o.id) };
}

const occOf = async (ctx: ScenarioContext, id: string) => {
  const o = await ctx.store.getOccurrence(id);
  if (!o) throw new Error(`occurrence ${id} vanished`);
  return o;
};
const statusOf = async (ctx: ScenarioContext, id: string) => (await occOf(ctx, id)).status;
const cardCalls = (ctx: ScenarioContext, occId: string) => ctx.provider.calls.filter((c) => c.metadata?.occurrence_id === occId);
const attemptsOf = (ctx: ScenarioContext, occId: string) => ctx.store.listAttempts({ occurrenceId: occId });
const paymentsOf = async (ctx: ScenarioContext, rentalId: string, occId: string) => (await ctx.payments(rentalId)).filter((p) => p.occurrenceId === occId);
const eventsOf = async (ctx: ScenarioContext, planId: string, occId: string | null, kind: string) =>
  (await ctx.store.listEvents(planId)).filter((e) => e.kind === kind && (occId === null || e.occurrenceId === occId));
const planStatus = async (ctx: ScenarioContext, planId: string) => (await ctx.store.getPlan(planId))?.status ?? null;
const sorted = (xs: number[]) => [...xs].sort((a, b) => a - b);

