export function engineDeps(ctx: ScenarioContext): EngineDeps {
  return { store: ctx.store, provider: ctx.provider, notifier: ctx.notifier, links: ctx.links };
}

/** MemoryPlanStore + SimulatedProvider('acct_sim') + recorders. Writes nothing anywhere. */
export function createMemoryContext(): ScenarioContext {
  const store = new MemoryPlanStore({ now: "2026-09-01T00:00:00.000Z" });
  const provider = new SimulatedProvider({ account: "acct_sim", mode: "test", fallback: "succeed" });
  const notifier = new RecordingNotifier();
  const links = new SimulatedLinkMinter();
  let n = 0;
  const ctx: ScenarioContext = {
    kind: "memory",
    store,
    provider,
    notifier,
    links,
    tick: (asOf) => runTick(engineDeps(ctx), { asOf }),
    at: (asOf) => {
      store.setNow(asOf);
      return Promise.resolve();
    },
    seedRental: (owedCents) => {
      n += 1;
      const r = { id: `rental-${n}`, tenantId: "tenant-1", customerId: `customer-${n}`, owedCents };
      store.addRental(r);
      return Promise.resolve({ rentalId: r.id, tenantId: r.tenantId, customerId: r.customerId });
    },
    payments: (rentalId) =>
      Promise.resolve(
        store.listPayments({ rentalId }).map((p) => ({
          id: p.id,
          occurrenceId: p.occurrenceId,
          amountCents: p.amountCents,
          refundCents: p.refundCents,
          method: p.method,
          providerRef: p.providerRef,
        })),
      ),
    revisionCount: (planId) => Promise.resolve(store.snapshot().revisions.filter((r) => r.planId === planId).length),
  };
  return ctx;
}

/** Run one scenario on a fresh context (memory unless another factory is given). */
export async function runScenario(s: Scenario, makeCtx?: () => ScenarioContext | Promise<ScenarioContext>): Promise<ScenarioRun> {
  const ctx = await (makeCtx ?? createMemoryContext)();
  return s.run(ctx);
}

