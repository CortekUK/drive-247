function deepEqual(a: unknown, b: unknown): boolean {
  if (Object.is(a, b)) return true;
  if (typeof a !== "object" || typeof b !== "object" || a === null || b === null) return false;
  if (Array.isArray(a) !== Array.isArray(b)) return false;
  if (Array.isArray(a)) {
    const bb = b as unknown[];
    return a.length === bb.length && a.every((x, i) => deepEqual(x, bb[i]));
  }
  const ao = a as Record<string, unknown>;
  const bo = b as Record<string, unknown>;
  const ka = Object.keys(ao).filter((k) => ao[k] !== undefined).sort();
  const kb = Object.keys(bo).filter((k) => bo[k] !== undefined).sort();
  return ka.length === kb.length && ka.every((k, i) => k === kb[i] && deepEqual(ao[k], bo[k]));
}

const jsonSafe = (v: unknown): unknown => (v === undefined ? null : JSON.parse(JSON.stringify(v)));

interface Rec {
  check(label: string, expected: unknown, actual: unknown): void;
  tick(asOf: string): Promise<TickResult>;
  note(key: string, value: unknown): void;
  planId: string | null;
  rentalId: string | null;
}

function define(id: string, title: string, why: string, body: (ctx: ScenarioContext, r: Rec) => Promise<void>): Scenario {
  return {
    id,
    title,
    why,
    async run(ctx: ScenarioContext): Promise<ScenarioRun> {
      const assertions: Assertion[] = [];
      const ticks: TickResult[] = [];
      const notes: Record<string, unknown> = {};
      const r: Rec = {
        planId: null,
        rentalId: null,
        check(label, expected, actual) {
          assertions.push({ label, expected: jsonSafe(expected), actual: jsonSafe(actual), pass: deepEqual(jsonSafe(expected), jsonSafe(actual)) });
        },
        async tick(asOf) {
          const t = (await ctx.tick(asOf)) as TickResult;
          ticks.push(t);
          return t;
        },
        note(key, value) {
          notes[key] = jsonSafe(value);
        },
      };
      let error: string | null = null;
      try {
        await body(ctx, r);
      } catch (e) {
        error = e instanceof Error ? `${e.name}: ${e.message}` : String(e);
        assertions.push({ label: "the script ran to the end without throwing", expected: null, actual: error, pass: false });
      }
      const tickErrors = ticks.flatMap((t) => t.errors.map((e) => ({ asOf: t.asOf, ...e })));
      assertions.push({ label: "no engine tick reported an error", expected: [], actual: jsonSafe(tickErrors), pass: tickErrors.length === 0 });
      const evidence = await collectEvidence(ctx, r, ticks, notes, error);
      return { id, title, assertions, pass: assertions.every((a) => a.pass), evidence };
    },
  };
}

async function collectEvidence(ctx: ScenarioContext, r: Rec, ticks: TickResult[], notes: Record<string, unknown>, error: string | null): Promise<ScenarioEvidence> {
  const ev: ScenarioEvidence = {
    context: ctx.kind,
    error,
    ticks: jsonSafe(ticks) as TickResult[],
    notes,
    plan: null,
    occurrences: [],
    attempts: [],
    keys: [],
    events: [],
    payments: [],
    providerCalls: ctx.provider.calls.map((c: ChargeRequest) => ({
      key: c.idempotencyKey,
      amountCents: c.amountCents,
      occurrenceId: c.metadata?.occurrence_id ?? null,
      attemptId: c.metadata?.attempt_id ?? null,
    })),
    charges: ctx.provider.allCharges(),
    refunds: [...ctx.provider.refunds],
    notifications: jsonSafe(ctx.notifier.sent) as unknown[],
    links: jsonSafe(ctx.links.minted) as unknown[],
  };
  try {
    if (r.planId) {
      ev.plan = await ctx.store.getPlan(r.planId);
      ev.occurrences = await ctx.store.listOccurrences(r.planId);
      ev.attempts = await ctx.store.listAttempts({ planId: r.planId });
      ev.keys = ev.attempts.map((a) => a.idempotencyKey);
      ev.events = await ctx.store.listEvents(r.planId);
    }
    if (r.rentalId) ev.payments = await ctx.payments(r.rentalId);
  } catch (e) {
    ev.error = `${ev.error ?? ""} evidence: ${e instanceof Error ? e.message : String(e)}`.trim();
  }
  return jsonSafe(ev) as ScenarioEvidence;
}

