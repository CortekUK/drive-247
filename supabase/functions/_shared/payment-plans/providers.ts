/**
 * Payment plans — the seams the engine talks through, and their simulations.
 *
 * The engine never imports Stripe, Resend or crypto. It is handed:
 *   PaymentProvider — moves money (Stripe in production, SimulatedProvider in
 *                     vitest and in the /dev simulator);
 *   Notifier        — tells a person something (email / operator bell);
 *   LinkMinter      — makes the stable /pay/plan/<token> URL.
 * The Deno implementations live in _shared/payment-plans-deno/ and are the
 * only files that know about the network.
 *
 * SimulatedProvider reproduces the parts of Stripe's behaviour the engine's
 * safety depends on, because a simulation that is kinder than Stripe proves
 * nothing:
 *   - an idempotency key's FIRST request decides the result; every replay of
 *     that key returns the stored result — including a stored FAILURE, which
 *     Stripe caches for 24 h just like a success;
 *   - a replay with different parameters is an `idempotency_error`, never a
 *     second charge;
 *   - a 5xx can arrive AFTER the money moved (`indeterminate_after_charge`):
 *     the caller saw an error, the card was charged, and only a replay of the
 *     same key (or a lookup by metadata) reveals it;
 *   - a 409 (`in_use`) stores nothing — the next request with that key is
 *     treated as the first.
 *
 * Canonical copy: supabase/functions/_shared/payment-plans/. The portal copy is
 * generated by scripts/sync-payment-plans.mjs — edit here, then sync.
 */

export interface ChargeRequest {
  amountCents: number;
  currency: string;
  idempotencyKey: string;
  /** Connected account (acct_…) the charge runs on; null = the platform account. */
  account: string | null;
  /**
   * OUR customers.id — never a provider customer id. The Stripe provider
   * resolves the live `cus_…` for this customer at charge time, because a
   * stored Stripe customer id goes stale across test/live and UK/UAE accounts
   * (the Kedic incident, _shared/customer-account.ts).
   */
  customerRef: string | null;
  /** The saved card (pm_…) chosen for the plan, or null to use the customer's default. */
  paymentMethodRef: string | null;
  /** Always carries occurrence_id, attempt_id, plan_id, tenant_id, rental_id, type='payment_plan'. */
  metadata: Record<string, string>;
}

export type ChargeOutcome =
  | { kind: "succeeded"; providerRef: string }
  | { kind: "declined"; providerRef: string | null; declineCode: string | null; errorCode: string | null; message?: string }
  | { kind: "indeterminate"; message?: string }
  | { kind: "in_use" };

export interface PaymentProvider {
  readonly name: "stripe" | "square" | "simulated";
  readonly mode: "test" | "live";
  readonly account: string | null;
  /**
   * Which Drive247 platform Stripe account the money lands under
   * (payments.platform_account). Optional so a provider that has no notion of
   * it (the simulation) can omit it; the engine then records 'uk'.
   */
  readonly platformAccount?: "uk" | "uae";
  charge(req: ChargeRequest): Promise<ChargeOutcome>;
  refund(providerRef: string, amountCents: number, idempotencyKey: string): Promise<{ ok: boolean; message?: string }>;
  /**
   * The charge made for an attempt, found by its metadata, NET of refunds —
   * null when there is none or it was refunded in full. Used by recovery
   * before any new key is ever used (design §7.1).
   */
  findByAttempt(attemptId: string): Promise<{ providerRef: string; amountCents: number } | null>;
}

export type NotificationKind = "reminder" | "link" | "due_manual" | "failed" | "alert";

export interface Notification {
  kind: NotificationKind;
  to: "customer" | "operator";
  planId: string;
  occurrenceId?: string;
  url?: string;
  amountCents?: number;
  dueDate?: string;
  detail?: Record<string, unknown>;
}

export interface Notifier {
  send(n: Notification): Promise<void>;
}

export interface LinkMinter {
  mint(occurrenceId: string): Promise<{ token: string; tokenHash: string; url: string }>;
}

