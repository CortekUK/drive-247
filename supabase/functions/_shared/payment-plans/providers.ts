/**
 * What the next NEW idempotency key on an occurrence gets:
 *   "succeed"                     — money moves, `succeeded`.
 *   { decline: code }             — `declined` with that code (stored: replays decline too).
 *   "indeterminate_after_charge"  — money moves, the caller sees a 5xx; a replay
 *                                   of the key returns `succeeded` with the same ref.
 *   "indeterminate_before_charge" — nothing moves, the caller sees a 5xx; nothing
 *                                   is stored, so a replay gets the next scripted outcome.
 *   "in_use"                      — 409; nothing moves, nothing is stored.
 */
export type ScriptedOutcome =
  | "succeed"
  | { decline: string }
  | "indeterminate_after_charge"
  | "indeterminate_before_charge"
  | "in_use";

/** Codes Stripe reports as an error `code` with no `decline_code`. */
const ERROR_CODE_ONLY = new Set([
  "rate_limit",
  "lock_timeout",
  "livemode_mismatch",
  "testmode_charges_only",
  "payment_intent_unexpected_state",
  "billing_invalid_mandate",
  "missing",
  "idempotency_error",
  "resource_missing",
  "parameter_missing",
  "parameter_unknown",
  "parameter_invalid_empty",
]);

interface StoredResult {
  request: ChargeRequest;
  outcome: ChargeOutcome;
}

interface SimCharge {
  idempotencyKey: string;
  providerRef: string;
  amountCents: number;
  occurrenceId: string;
  attemptId: string | null;
  refundedCents: number;
}

export class SimulatedProvider implements PaymentProvider {
  readonly name = "simulated" as const;
  readonly mode: "test" | "live";
  readonly account: string | null;
  readonly platformAccount = "uk" as const;

  /** Every charge call, replays included, in order. */
  readonly calls: ChargeRequest[] = [];
  /** Every refund that succeeded. */
  readonly refunds: { providerRef: string; amountCents: number }[] = [];

  private readonly fallback: ScriptedOutcome;
  private readonly queues = new Map<string, ScriptedOutcome[]>();
  private readonly stored = new Map<string, StoredResult>();
  private readonly charges: SimCharge[] = [];
  private readonly refundScript: ("ok" | "fail")[] = [];
  private readonly refundKeys = new Map<string, { ok: boolean; message?: string }>();
  private refCounter = 0;

  constructor(opts?: { account?: string; mode?: "test" | "live"; fallback?: ScriptedOutcome }) {
    // The design's base fixture charges on `acct_sim`, so keys read
    // pp:acct_sim:{occ}:{n} (design §10.1).
    this.account = opts?.account ?? "acct_sim";
    this.mode = opts?.mode ?? "test";
    this.fallback = opts?.fallback ?? "succeed";
  }

  /** Script the outcomes of the next NEW keys charged for `occurrenceId`, in order. */
  queue(occurrenceId: string, outcomes: ScriptedOutcome[]): void {
    const q = this.queues.get(occurrenceId) ?? [];
    q.push(...outcomes);
    this.queues.set(occurrenceId, q);
  }

  /** Script the next refunds: 'fail' makes one refund report failure (for the compensation path). */
  scriptRefunds(outcomes: ("ok" | "fail")[]): void {
    this.refundScript.push(...outcomes);
  }

  /** Money that actually moved for an occurrence (a replay moves nothing new). */
  chargesFor(occurrenceId: string): { idempotencyKey: string; providerRef: string; amountCents: number }[] {
    return this.charges
      .filter((c) => c.occurrenceId === occurrenceId)
      .map(({ idempotencyKey, providerRef, amountCents }) => ({ idempotencyKey, providerRef, amountCents }));
  }

  /** Every charge that moved money, with what has been refunded of it. */
  allCharges(): { idempotencyKey: string; providerRef: string; amountCents: number; occurrenceId: string; refundedCents: number }[] {
    return this.charges.map(({ idempotencyKey, providerRef, amountCents, occurrenceId, refundedCents }) => ({
      idempotencyKey,
      providerRef,
      amountCents,
      occurrenceId,
      refundedCents,
    }));
  }

  private nextRef(): string {
    this.refCounter += 1;
    return `sim_pi_${this.refCounter}`;
  }

  private take(occurrenceId: string): ScriptedOutcome {
    const q = this.queues.get(occurrenceId);
    if (q && q.length > 0) return q.shift()!;
    return this.fallback;
  }

  charge(req: ChargeRequest): Promise<ChargeOutcome> {
    const snapshot: ChargeRequest = { ...req, metadata: { ...req.metadata } };
    this.calls.push(snapshot);

    const prior = this.stored.get(req.idempotencyKey);
    if (prior) {
      // Stripe compares the parameters of a replay with the first request.
      const same =
        prior.request.amountCents === req.amountCents &&
        prior.request.currency === req.currency &&
        prior.request.account === req.account;
      if (!same) {
        return Promise.resolve({
          kind: "declined",
          providerRef: null,
          declineCode: null,
          errorCode: "idempotency_error",
          message: "Keys for idempotent requests can only be used with the same parameters they were first used with.",
        });
      }
      return Promise.resolve(prior.outcome);
    }

    const occurrenceId = req.metadata?.occurrence_id ?? "";
    const scripted = this.take(occurrenceId);

    const moveMoney = (): string => {
      const providerRef = this.nextRef();
      this.charges.push({
        idempotencyKey: req.idempotencyKey,
        providerRef,
        amountCents: req.amountCents,
        occurrenceId,
        attemptId: req.metadata?.attempt_id ?? null,
        refundedCents: 0,
      });
      return providerRef;
    };

    let outcome: ChargeOutcome;
    if (scripted === "succeed") {
      outcome = { kind: "succeeded", providerRef: moveMoney() };
      this.stored.set(req.idempotencyKey, { request: snapshot, outcome });
    } else if (scripted === "indeterminate_after_charge") {
      const providerRef = moveMoney();
      // Stored as the success it really was; only THIS response was lost.
      this.stored.set(req.idempotencyKey, { request: snapshot, outcome: { kind: "succeeded", providerRef } });
      outcome = { kind: "indeterminate", message: "Simulated 5xx after the charge was made" };
    } else if (scripted === "indeterminate_before_charge") {
      outcome = { kind: "indeterminate", message: "Simulated 5xx before the charge was made" };
    } else if (scripted === "in_use") {
      outcome = { kind: "in_use" };
    } else {
      const code = scripted.decline;
      const errorOnly = ERROR_CODE_ONLY.has(code);
      outcome = {
        kind: "declined",
        // A declined PaymentIntent still exists at Stripe with an id.
        providerRef: this.nextRef(),
        declineCode: errorOnly ? null : code,
        errorCode: errorOnly ? code : "card_declined",
        message: `Simulated decline: ${code}`,
      };
      this.stored.set(req.idempotencyKey, { request: snapshot, outcome });
    }
    return Promise.resolve(outcome);
  }

  refund(providerRef: string, amountCents: number, idempotencyKey: string): Promise<{ ok: boolean; message?: string }> {
    const replay = this.refundKeys.get(idempotencyKey);
    if (replay) return Promise.resolve(replay);
    let result: { ok: boolean; message?: string };
    const scripted = this.refundScript.shift();
    const charge = this.charges.find((c) => c.providerRef === providerRef);
    if (scripted === "fail") {
      result = { ok: false, message: "Simulated refund failure" };
    } else if (!charge) {
      result = { ok: false, message: `No such charge: ${providerRef}` };
    } else if (!Number.isInteger(amountCents) || amountCents < 1 || charge.refundedCents + amountCents > charge.amountCents) {
      result = { ok: false, message: "Refund amount exceeds the charge" };
    } else {
      charge.refundedCents += amountCents;
      this.refunds.push({ providerRef, amountCents });
      result = { ok: true };
    }
    this.refundKeys.set(idempotencyKey, result);
    return Promise.resolve(result);
  }

  findByAttempt(attemptId: string): Promise<{ providerRef: string; amountCents: number } | null> {
    const charge = this.charges.find((c) => c.attemptId === attemptId);
    if (!charge) return Promise.resolve(null);
    const net = charge.amountCents - charge.refundedCents;
    return Promise.resolve(net > 0 ? { providerRef: charge.providerRef, amountCents: net } : null);
  }
}

/** Records every notification; sends nothing. */
export class RecordingNotifier implements Notifier {
  readonly sent: Notification[] = [];
  send(n: Notification): Promise<void> {
    this.sent.push({ ...n, detail: n.detail ? { ...n.detail } : undefined });
    return Promise.resolve();
  }
}

/**
 * FNV-1a, 32-bit, hex. NOT a security hash — the simulated minter only needs
 * a deterministic, distinct stand-in so evidence JSON is stable. The Deno
 * minter stores a real SHA-256.
 */
function fnv1a(text: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, "0");
}

/** Deterministic links for the simulator: tokens `simtok-{n}`, URLs on a non-routable host. */
export class SimulatedLinkMinter implements LinkMinter {
  readonly minted: { occurrenceId: string; token: string; tokenHash: string; url: string }[] = [];
  private readonly base: string;
  private counter = 0;

  constructor(opts?: { baseUrl?: string }) {
    this.base = (opts?.baseUrl ?? "https://simulated.invalid").replace(/\/+$/, "");
  }

  mint(occurrenceId: string): Promise<{ token: string; tokenHash: string; url: string }> {
    this.counter += 1;
    const token = `simtok-${this.counter}`;
    const tokenHash = `sim-${fnv1a(`${token}:${occurrenceId}`)}`;
    const url = `${this.base}/pay/plan/${token}`;
    this.minted.push({ occurrenceId, token, tokenHash, url });
    return Promise.resolve({ token, tokenHash, url });
  }
}
