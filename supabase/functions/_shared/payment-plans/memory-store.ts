  /** pp_cancel_plan. */
  async cancelPlan(planId: string, actorId?: string | null, reason?: string): Promise<void> {
    const plan = this.requirePlan(planId);
    const occs = this.occsOf(planId);
    if (occs.some((o) => o.status === "processing")) {
      throw new PlanStoreError("attempt_in_flight", `pp_cancel_plan: plan ${planId} has a charge in flight; try again when it settles`);
    }
    if (plan.status !== "active" && plan.status !== "paused") throw new PlanStoreError("illegal_transition", `pp_cancel_plan: plan ${planId} is not active or paused`);
    plan.status = "cancelled";
    plan.cancelledAt = this.clock;
    plan.updatedAt = this.clock;
    for (const o of occs) {
      for (const a of this.attemptsOf(o.id)) {
        if (OPEN_ATTEMPT.includes(a.status)) {
          this.setAttemptStatus(a, "abandoned");
          a.finishedAt = this.clock;
          a.errorMessage = "plan cancelled";
        }
      }
    }
    for (const o of occs) if (OPEN.includes(o.status)) this.setStatus(o, "cancelled");
    this.pushEvent({ planId, kind: "plan_cancelled", actorId: actorId ?? null, detail: { reason: reason ?? null } });
    return Promise.resolve();
  }

  /** pp_move_occurrence. */
  async moveOccurrence(occurrenceId: string, to: ISODate, actorId?: string | null): Promise<void> {
    if (!isISODate(to)) throw new PlanStoreError("invalid_input", "pp_move_occurrence: a date is required");
    const occ = this.requireOcc(occurrenceId);
    if (!OPEN.includes(occ.status)) throw new PlanStoreError("refused", `pp_move_occurrence: occurrence ${occurrenceId} is ${occ.status}`);
    const plan = this.requirePlan(occ.planId);
    const from = occ.dueDate;
    const at = dueAtUtc(to, plan.chargeLocalTime, plan.timezone);
    occ.movedFrom = occ.movedFrom ?? from;
    occ.dueDate = to;
    occ.dueAt = at;
    // A failed occurrence moved to a date is retried on that date.
    occ.nextAttemptAt = occ.status === "failed" ? at : null;
    occ.updatedAt = this.clock;
    this.pushEvent({ planId: plan.id, occurrenceId, kind: "occurrence_moved", actorId: actorId ?? null, detail: { from, to } });
    return Promise.resolve();
  }

  /** pp_skip_occurrence. */
  async skipOccurrence(occurrenceId: string, actorId?: string | null): Promise<void> {
    const occ = this.requireOcc(occurrenceId);
    if (!OPEN.includes(occ.status)) throw new PlanStoreError("refused", `pp_skip_occurrence: occurrence ${occurrenceId} is ${occ.status}`);
    if (this.openAttempt(occ.id)) throw new PlanStoreError("attempt_in_flight", `pp_skip_occurrence: occurrence ${occurrenceId} has an open attempt`);
    const next = this.occsOf(occ.planId).find((o) => o.seq > occ.seq && OPEN.includes(o.status));
    if (!next) {
      throw new PlanStoreError("refused", `pp_skip_occurrence: occurrence ${occurrenceId} is the last open occurrence; its amount has nowhere to go`);
    }
    const remaining = Math.max(0, occ.amountCents - occ.amountPaidCents);
    next.amountCents += remaining;
    next.updatedAt = this.clock;
    this.setStatus(occ, "skipped");
    this.pushEvent({
      planId: occ.planId,
      occurrenceId,
      kind: "occurrence_skipped",
      actorId: actorId ?? null,
      amountCents: remaining,
      detail: { rolledInto: next.id, rolledIntoSeq: next.seq },
    });
    return Promise.resolve();
  }

