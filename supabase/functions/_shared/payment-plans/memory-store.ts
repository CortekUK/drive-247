export const TRANSITIONS: Readonly<Record<OccurrenceStatus, readonly OccurrenceStatus[]>> = {
  scheduled: ["due", "paid", "partially_paid", "skipped", "superseded", "cancelled"],
  due: ["processing", "paid", "partially_paid", "requires_action", "failed", "skipped", "superseded", "cancelled"],
  processing: ["paid", "partially_paid", "failed", "requires_action", "due"],
  requires_action: ["processing", "paid", "partially_paid", "failed", "due", "skipped", "superseded", "cancelled"],
  partially_paid: ["processing", "paid", "failed", "requires_action", "due", "skipped", "superseded", "cancelled"],
  failed: ["processing", "due", "paid", "partially_paid", "requires_action", "skipped", "superseded", "cancelled"],
  paid: ["partially_paid", "due"],
  skipped: ["due"],
  superseded: [],
  cancelled: [],
  waived: [],
};

export const ATTEMPT_TRANSITIONS: Readonly<Record<AttemptStatus, readonly AttemptStatus[]>> = {
  claimed: ["in_flight", "succeeded", "failed", "requires_action", "indeterminate", "abandoned"],
  in_flight: ["succeeded", "failed", "requires_action", "indeterminate", "abandoned"],
  indeterminate: ["succeeded", "failed", "requires_action", "abandoned"],
  requires_action: ["succeeded", "failed", "abandoned"],
  abandoned: ["succeeded"],
  failed: ["succeeded"],
  succeeded: [],
};

export function canTransition(from: OccurrenceStatus, to: OccurrenceStatus): boolean {
  return from === to || TRANSITIONS[from].includes(to);
}

export function canAttemptTransition(from: AttemptStatus, to: AttemptStatus): boolean {
  return from === to || ATTEMPT_TRANSITIONS[from].includes(to);
}

/** Statuses a claim may start from (pp_claim); manual also takes 'scheduled'. */
export const CLAIMABLE: readonly OccurrenceStatus[] = ["due", "failed", "requires_action", "partially_paid"];
/** A plan whose occurrences are all here is complete (pp__maybe_complete_plan). */
export const DONE: readonly OccurrenceStatus[] = ["paid", "skipped", "waived", "superseded", "cancelled"];
/** Open and not held by a card charge: what operators act on, what reminders cover. */
export const OPEN: readonly OccurrenceStatus[] = ["scheduled", "due", "failed", "requires_action", "partially_paid"];
const TERMINAL: readonly OccurrenceStatus[] = ["superseded", "cancelled", "waived"];
const OPEN_ATTEMPT: readonly AttemptStatus[] = ["claimed", "in_flight"];
const STALE_CANDIDATE: readonly AttemptStatus[] = ["claimed", "in_flight", "indeterminate"];

