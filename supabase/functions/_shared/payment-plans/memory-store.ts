  /** pp_create_plan. */
  async createPlan(input: { plan: Omit<PlanRow, "id" | "version" | "status">; occurrences: OccurrenceDraft[]; actorId?: string | null }): Promise<string> {
    const p = input.plan;
    const rental = this.requireRental(p.rentalId);
    if (rental.tenantId !== p.tenantId) throw new PlanStoreError("invalid_input", `pp_create_plan: rental ${p.rentalId} does not belong to tenant ${p.tenantId}`);
    if (rental.customerId !== p.customerId) throw new PlanStoreError("invalid_input", `pp_create_plan: rental ${p.rentalId} does not belong to customer ${p.customerId}`);
    for (const existing of this.plans.values()) {
      if (existing.rentalId === p.rentalId && (existing.status === "active" || existing.status === "paused")) {
        throw new PlanStoreError("plan_exists", `Rental ${p.rentalId} already has a live plan (${existing.id})`);
      }
    }
    const id = this.nextId("plan");
    const plan: PlanState = {
      ...clone(p),
      currency: (p.currency || "usd").toLowerCase(),
      id,
      status: "active",
      version: 1,
      createdAt: this.clock,
      updatedAt: this.clock,
      pausedAt: null,
      cancelledAt: null,
      completedAt: null,
      createdBy: input.actorId ?? null,
    };
    this.plans.set(id, plan);
    let n: number;
    try {
      n = this.insertOccurrences(plan, input.occurrences);
    } catch (e) {
      this.plans.delete(id); // one transaction
      this.counters.plan -= 1;
      throw e;
    }
    this.pushEvent({ planId: id, kind: "plan_created", actorId: input.actorId ?? null, detail: { occurrences: n, version: 1 } });
    return Promise.resolve(id);
  }

  /** pp_replace_future. */
  async replaceFuture(input: {
    planId: string;
    expectedVersion: number;
    planPatch: Partial<Omit<PlanRow, "id" | "tenantId" | "rentalId" | "customerId" | "version">>;
    occurrences: OccurrenceDraft[];
    actorId?: string | null;
    reason: string;
  }): Promise<number> {
    if (!input.reason || !input.reason.trim()) throw new PlanStoreError("invalid_input", "pp_replace_future: a reason is required");
    const plan = this.requirePlan(input.planId);
    if (plan.version !== input.expectedVersion) {
      throw new PlanStoreError("version_conflict", `pp_replace_future: version conflict on plan ${plan.id} (expected ${input.expectedVersion}, found ${plan.version})`);
    }
    if (plan.status !== "active" && plan.status !== "paused") throw new PlanStoreError("refused", `pp_replace_future: plan ${plan.id} is ${plan.status}`);
    const occs = this.occsOf(plan.id);
    if (occs.some((o) => o.status === "processing")) {
      throw new PlanStoreError("attempt_in_flight", `pp_replace_future: plan ${plan.id} has a charge in flight; try again when it settles`);
    }
    const patch = input.planPatch ?? {};
    for (const k of Object.keys(patch)) {
      if (!PATCHABLE.has(k)) throw new PlanStoreError("invalid_input", `pp_replace_future: field "${k}" cannot be patched`);
    }
    if (!Array.isArray(input.occurrences) || input.occurrences.length === 0) {
      throw new PlanStoreError("invalid_input", "payment plan: at least one occurrence is required");
    }
    const merged: PlanState = { ...plan, ...clone(patch) } as PlanState;
    // Validate the new drafts against the MERGED plan before anything moves.
    for (const d of input.occurrences) {
      if (!isISODate(d.dueDate)) throw new PlanStoreError("invalid_input", "occurrence draft: dueDate is required");
      dueAtUtc(d.dueDate, merged.chargeLocalTime, merged.timezone);
    }

    const before = this.toPlanRow(plan);
    const open = ["scheduled", "due", "failed", "requires_action", "partially_paid"];
    for (const o of occs) {
      if (!open.includes(o.status)) continue;
      // An open link or manual claim goes with its occurrence; a late payment
      // on it is still recordable (abandoned → succeeded).
      for (const a of this.attemptsOf(o.id)) {
        if (OPEN_ATTEMPT.includes(a.status)) {
          this.setAttemptStatus(a, "abandoned");
          a.finishedAt = this.clock;
          a.errorMessage = "superseded by a plan change";
        }
      }
      this.setStatus(o, "superseded");
    }
    Object.assign(plan, clone(patch), { version: plan.version + 1, updatedAt: this.clock });
    plan.currency = (plan.currency || "usd").toLowerCase();
    this.insertOccurrences(plan, input.occurrences);

    this.revisions.push({
      id: this.nextId("rev"),
      tenantId: plan.tenantId,
      planId: plan.id,
      version: plan.version,
      changedBy: input.actorId ?? null,
      reason: input.reason,
      before,
      after: this.toPlanRow(plan),
      createdAt: this.clock,
    });
    this.pushEvent({ planId: plan.id, kind: "plan_changed", actorId: input.actorId ?? null, detail: { version: plan.version, reason: input.reason } });
    return Promise.resolve(plan.version);
  }

