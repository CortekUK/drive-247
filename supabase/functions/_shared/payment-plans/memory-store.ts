/**
 * Payment plans — the in-memory store.
 *
 * The same contract as the pp_* SQL functions in
 * supabase/migrations/20260925120100_payment_plans.sql (design §5), held in
 * plain maps so the real engine can run in vitest and in the browser simulator
 * (/dev) without a database. It is only trusted because the parity suite runs
 * the same scenarios against the PGlite store (the real SQL) and the two
 * agree — so every method below mirrors ONE SQL function, and says which.
 * Where this file and the SQL disagree, the SQL is right and this file is the
 * bug.
 *
 * The rental's money is ONE number per rental, `owedCents` — what the rental
 * still owes after every payment (negative = unapplied credit, which the SQL
 * nets out in pp_rental_owed_cents). The real ledger's FIFO allocation is out
 * of scope here; `rentalOwedCents` is `max(0, owedCents)`.
 *
 * Occurrence state machine (design §6, trigger pp_trg_occurrence_guard):
 *   scheduled → due | paid | partially_paid | skipped | superseded | cancelled
 *   due       → processing | paid | partially_paid | requires_action | failed | skipped | superseded | cancelled
 *   processing→ paid | partially_paid | failed | requires_action | due
 *   requires_action → processing | paid | partially_paid | failed | due | skipped | superseded | cancelled
 *   partially_paid  → processing | paid | failed | requires_action | due | skipped | superseded | cancelled
 *   failed    → processing | due | paid | partially_paid | requires_action | skipped | superseded | cancelled
 *   paid      → partially_paid | due            (refunds only)
 *   skipped   → due                             (operator undo)
 *   superseded, cancelled, waived: terminal
 * Attempt state machine (trigger pp_trg_attempt_guard): claimed → anything;
 * in_flight → succeeded | failed | requires_action | indeterminate | abandoned;
 * indeterminate → succeeded | failed | requires_action | abandoned;
 * requires_action → succeeded | failed | abandoned; abandoned and failed →
 * succeeded only (late money is real money); succeeded is terminal.
 * Any other transition THROWS (PlanStoreError 'illegal_transition'), as the
 * triggers raise.
 *
 * The readings the SQL header lists as "deviations from the design text",
 * mirrored here:
 *   - only an auto_charge claim moves the occurrence to 'processing'; a link or
 *     manual claim is held by its attempt row alone, and that attempt's
 *     failure or release never moves the occurrence (S3, S4, S18);
 *   - a manual claim may take a 'scheduled' occurrence (S10);
 *   - collectDue returns partially_paid rows past due_at, and 'due' rows only
 *     once due_at has passed (S10, S12);
 *   - pp_claim refuses an auto_charge on an occurrence carrying a refunded
 *     payment (D12).
 *
 * Ids are deterministic (plan-1, occ-1, att-1, pay-1, evt-1, rev-1) so
 * evidence JSON is stable across runs.
 *
 * Canonical copy: supabase/functions/_shared/payment-plans/. The portal copy is
 * generated by scripts/sync-payment-plans.mjs — edit here, then sync.
 */

