  async recordExternalPayment(rentalId: string, amountCents: number, paymentDate: ISODate): Promise<string> {
    const rental = this.requireRental(rentalId);
    if (!Number.isSafeInteger(amountCents) || amountCents < 1) throw new PlanStoreError("invalid_input", "amount must be ≥ 1 cent");
    if (!isISODate(paymentDate)) throw new PlanStoreError("invalid_input", `Bad payment date ${paymentDate}`);
    const id = this.nextId("pay");
    this.payments.set(id, {
      id,
      tenantId: rental.tenantId,
      rentalId,
      customerId: rental.customerId,
      occurrenceId: null,
      attemptId: null,
      amountCents,
      refundCents: 0,
      status: "Completed",
      method: "External",
      paymentDate,
      paymentProvider: null,
      providerRef: null,
      providerAccount: null,
      providerMode: null,
      platformAccount: null,
      checkoutSessionId: null,
      bookingSource: "external",
      createdAt: this.clock,
    });
    rental.owedCents -= amountCents;
    return Promise.resolve(id);
  }

  async refundPayment(paymentId: string, amountCents: number): Promise<void> {
    const p = this.payments.get(paymentId);
    if (!p) throw new PlanStoreError("not_found", `Payment ${paymentId} not found`);
    if (!Number.isSafeInteger(amountCents) || amountCents < 1 || p.refundCents + amountCents > p.amountCents) {
      throw new PlanStoreError("invalid_input", "Refund must be ≥ 1 cent and no more than what is left of the payment");
    }
    p.refundCents += amountCents;
    p.status = p.refundCents >= p.amountCents ? "Refunded" : "Partial Refund";
    this.requireRental(p.rentalId).owedCents += amountCents;
    // D12: the linked occurrence re-opens (paid → due / partially_paid) with
    // attempt_no untouched, and pp_claim now refuses to auto-charge it.
    if (p.occurrenceId) this.settle(this.requireOcc(p.occurrenceId));
    return Promise.resolve();
  }
