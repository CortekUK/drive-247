  async settleOccurrence(occurrenceId: string): Promise<OccurrenceRow> {
    const occ = this.requireOcc(occurrenceId);
    this.settle(occ);
    return Promise.resolve(this.toOccRow(occ));
  }

  /** pp_stale_attempts: created at or before as_of − lease. */
  async staleAttempts(olderThanSeconds: number, asOf: string): Promise<AttemptRow[]> {
    const out = [...this.attempts.values()]
      .filter((a) => STALE_CANDIDATE.includes(a.status) && a.method !== "checkout_link" && secondsBetween(a.createdAt, asOf) >= olderThanSeconds)
      .sort((a, b) => compareInstants(a.createdAt, b.createdAt) || (a.id < b.id ? -1 : 1));
    return Promise.resolve(out.map((a) => this.toAttemptRow(a)));
  }

