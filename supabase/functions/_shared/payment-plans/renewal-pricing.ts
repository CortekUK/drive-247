/** The plan's unit → auto-extend's rentals.auto_extend_period_unit. */
export const AUTO_EXTEND_UNIT: Readonly<Record<RenewalPeriodUnit, "Daily" | "Weekly" | "Monthly">> = {
  day: "Daily",
  week: "Weekly",
  month: "Monthly",
};

/** rentals.auto_extend_period_unit / rental_period_type → the plan's unit. Anything else is a week, as in addPeriod. */
export function renewalUnitFrom(value: string | null | undefined): RenewalPeriodUnit {
  const v = String(value ?? "").toLowerCase();
  if (v === "daily" || v === "day") return "day";
  if (v === "monthly" || v === "month") return "month";
  return "week";
}

export interface RenewalPeriod {
  periodStart: ISODate; // inclusive
  periodEnd: ISODate; // exclusive — the rental's new end date once paid
  days: number;
}

/** The period that starts on `start`, dated exactly as auto-extend dates a renewal (addPeriod). */
export function renewalPeriod(start: ISODate, unit: RenewalPeriodUnit, count: number): RenewalPeriod {
  const { newEndDate, days } = addPeriod(start, AUTO_EXTEND_UNIT[unit], count);
  return { periodStart: start, periodEnd: newEndDate, days };
}

/** A dollar amount already rounded to the cent (round2's output) → integer cents, exactly (never `x * 100`). */
export function dollarsToCents(dollars: number): number {
  if (!Number.isFinite(dollars)) throw new RangeError(`Not an amount: ${dollars}`);
  return decimalToCents(dollars.toFixed(2));
}

/**
 * One renewal period's price, exactly as auto-extend prices a period that has
 * no per-occurrence override: computeBreakdown(discountedRate(rental), tenant)
 * — the discounted per-period rate, plus tax, plus the service fee. The cents
 * are the ledger rows' own values; the total is their sum (what the ledger
 * will say is owed). Insurance is NOT here: a premium joins the period only
 * once a policy has been bought (renewals.ts, A4).
 *
 * Throws PlanRuleError('amount_too_small') when the period would cost nothing
 * — auto-extend skips such a rental, a plan refuses to be set up on one.
 */
export function renewalBreakdownCents(p: Pick<RenewalPricingInputs, "monthlyAmount" | "discountApplied" | "tenant">): RenewalBreakdown {
  const bd = computeBreakdown(discountedRate({ monthly_amount: p.monthlyAmount, discount_applied: p.discountApplied }), p.tenant);
  const rentalCents = dollarsToCents(bd.rental);
  const taxCents = dollarsToCents(bd.tax);
  const serviceFeeCents = dollarsToCents(bd.serviceFee);
  const totalCents = rentalCents + taxCents + serviceFeeCents;
  if (totalCents < 1) {
    throw new PlanRuleError("amount_too_small", "This rental has no per-period price (its rate less its discount is $0), so there is nothing to renew for");
  }
  return { rentalCents, taxCents, serviceFeeCents, totalCents };
}

/** Does this coverage ask for any Bonzah product? */
export function hasCoverage(c: { cdw?: boolean; rcli?: boolean; sli?: boolean; pai?: boolean } | null | undefined): boolean {
  return !!c && (!!c.cdw || !!c.rcli || !!c.sli || !!c.pai);
}
