/** Post a renewal period this many days before it falls due (the −2 reminder's day). */
export const RENEWAL_POST_LEAD_DAYS = 2;
/** The most periods one Extend may add. */
export const MAX_EXTEND_PERIODS = 12;

export type RenewalStore = PlanStore & PlanOperations & PlanLookups & RenewalOperations;

export interface RenewalDeps {
  store: RenewalStore;
  notifier: Notifier;
  insurer?: RenewalInsurer | null;
}

/** Does this store carry the renewal operations? (A store without them skips the stage.) */
export function storeHasRenewals(store: unknown): store is RenewalStore {
  const s = store as Partial<RenewalOperations> | null;
  return (
    !!s &&
    typeof s.listRenewalPlans === "function" &&
    typeof s.renewalPricing === "function" &&
    typeof s.appendRenewalPeriod === "function" &&
    typeof s.postRenewalPeriod === "function" &&
    typeof s.recordRenewalInsurance === "function" &&
    typeof s.reconcileRenewals === "function"
  );
}

export type InsuranceResultKind = "insured" | "not_insurable" | "failed" | "retry_later" | "none";

export interface InsuranceResult {
  occurrenceId: string;
  outcome: InsuranceResultKind;
  premiumCents?: number;
  policyRef?: string;
  coveredFrom?: ISODate;
  coveredTo?: ISODate;
  reason?: string;
}

export interface RenewalStageResult {
  reconciled: string[];
  appended: { planId: string; occurrenceId: string; periodStart: ISODate; periodEnd: ISODate }[];
  posted: { planId: string; occurrenceId: string; extensionId: string; totalCents: number }[];
  insurance: InsuranceResult[];
  errors: { planId?: string; occurrenceId?: string; message: string }[];
}

const message = (e: unknown): string => (e instanceof Error ? e.message : String(e));

async function safeSend(notifier: Notifier, n: Notification): Promise<void> {
  try {
    await notifier.send(n);
  } catch {
    /* a notification never changes what happens to money */
  }
}

const isLive = (o: OccurrenceRow): boolean => !!o.renews && o.status !== "superseded" && o.status !== "cancelled";
const SETTLED = new Set(["paid", "skipped", "waived"]);
const UNTOUCHED = new Set(["scheduled", "due"]);

/**
 * Where the next renewal period starts: the later of the rental's end date and
 * the end of the plan's last live renewal period — so a period can never leave
 * free days or bill days twice (pp_append_renewal_period enforces the same).
 */
export function renewalChainStart(rentalEnd: ISODate | null, occurrences: OccurrenceRow[]): ISODate | null {
  let chain: ISODate | null = rentalEnd;
  for (const o of occurrences) {
    if (!isLive(o) || !o.periodEnd) continue;
    if (!chain || compareDates(o.periodEnd, chain) > 0) chain = o.periodEnd;
  }
  return chain;
}

/**
 * The draft of the renewal period starting on `start`: dated by addPeriod (as
 * auto-extend dates it), priced by renewalBreakdownCents, due on its first day
 * unless `dueDate` says otherwise (an operator's Extend is due today).
 */
export function nextRenewalDraft(
  start: ISODate,
  renewal: { periodUnit: RenewalPeriodUnit; periodCount: number },
  pricing: Pick<RenewalPricingInputs, "monthlyAmount" | "discountApplied" | "tenant">,
  dueDate?: ISODate,
): OccurrenceDraft {
  const period = renewalPeriod(start, renewal.periodUnit, renewal.periodCount);
  const bd = renewalBreakdownCents(pricing);
  return {
    seq: 1, // pp_append_renewal_period assigns the real one
    dueDate: dueDate ?? start,
    periodStart: period.periodStart,
    periodEnd: period.periodEnd,
    days: period.days,
    amountCents: bd.totalCents,
    isStub: false,
  };
}

/** Normalise a coverage to the four booleans, or null when it buys nothing. */
export function normalizeCoverage(c: RenewalCoverage | null | undefined): RenewalCoverage | null {
  if (!hasCoverage(c)) return null;
  return { cdw: !!c!.cdw, rcli: !!c!.rcli, sli: !!c!.sli, pai: !!c!.pai };
}

// ─────────────────────────────────────────────────────────────────────────────
// Posting and insuring one period
// ─────────────────────────────────────────────────────────────────────────────

interface PostOptions {
  coverage: RenewalCoverage | null;
  giveDaysNow: boolean;
  actorId: string | null;
  /** An automatic period (the renewal stage), not an operator's Extend. */
  automatic: boolean;
}

async function postPeriod(deps: RenewalDeps, plan: PlanRow, occ: OccurrenceRow, pricing: RenewalPricingInputs, opts: PostOptions): Promise<PostRenewalResult> {
  const breakdown = renewalBreakdownCents(pricing);
  const posted = await deps.store.postRenewalPeriod({
    occurrenceId: occ.id,
    breakdown,
    insuranceRequested: hasCoverage(opts.coverage),
    giveDaysNow: opts.giveDaysNow,
    actorId: opts.actorId,
  });
  // A5, automatic periods: the plan's own setting decides. The server records
  // the choice and asks the operator to send it (the portal's /api/esign is
  // the only sender of an 'extension' agreement today).
  if (posted.posted && opts.automatic && plan.renewal?.sendAgreementEachPeriod) {
    const inserted = await deps.store.recordEvent({
      planId: plan.id,
      occurrenceId: occ.id,
      kind: "agreement_choice",
      dedupeKey: `agreement_choice:auto:${occ.id}`,
      detail: { sendAgreement: true, automatic: true, extensionIds: [posted.extensionId], occurrenceIds: [occ.id] },
    });
    if (inserted) {
      await safeSend(deps.notifier, {
        kind: "alert",
        to: "operator",
        planId: plan.id,
        occurrenceId: occ.id,
        detail: {
          problem: "extension_agreement_due",
          message: `A new period (${occ.periodStart} → ${occ.periodEnd}) was added to this renewing rental, and its plan sends an extension agreement for each period — send it from the rental page`,
        },
      });
    }
  }
  return posted;
}

/**
 * A4 for one posted period whose cover is undecided. `giveUp`: a transient
 * failure is final now (the period is due, or the operator is waiting) —
 * the period is then charged without insurance, and the operator told.
 */
async function insurePeriod(
  deps: RenewalDeps,
  plan: PlanRow,
  occ: OccurrenceRow,
  coverage: RenewalCoverage | null,
  asOf: string,
  giveUp: boolean,
): Promise<InsuranceResult> {
  const base = { occurrenceId: occ.id };
  const periodText = `${occ.periodStart} → ${occ.periodEnd}`;
  const decide = async (outcome: "not_insurable" | "failed", reason: string): Promise<InsuranceResult> => {
    await deps.store.recordRenewalInsurance({ occurrenceId: occ.id, outcome, reason });
    await safeSend(deps.notifier, {
      kind: "alert",
      to: "operator",
      planId: plan.id,
      occurrenceId: occ.id,
      detail: { problem: "insurance_not_bought", message: `No insurance was bought or charged for ${periodText}: ${reason}` },
    });
    return { ...base, outcome, reason };
  };

  if (!hasCoverage(coverage)) return decide("failed", "the cover chosen for this period was not kept; buy it from the rental's insurance timeline");
  if (!deps.insurer) return decide("failed", "insurance cannot be bought from here");
  if (!occ.extensionId || !occ.periodStart || !occ.periodEnd) throw new PlanStoreError("invalid_input", `Occurrence ${occ.id} is not a posted renewal period`);

  let outcome: InsureOutcome;
  try {
    outcome = await deps.insurer.insure({
      planId: plan.id,
      occurrenceId: occ.id,
      tenantId: plan.tenantId,
      rentalId: plan.rentalId,
      customerId: plan.customerId,
      extensionId: occ.extensionId,
      periodStart: occ.periodStart,
      periodEnd: occ.periodEnd,
      coverage: coverage as RenewalCoverage,
      asOf,
    });
  } catch (e) {
    outcome = { kind: "retry_later", reason: message(e) };
  }

  switch (outcome.kind) {
    case "insured": {
      await deps.store.recordRenewalInsurance({
        occurrenceId: occ.id,
        outcome: "insured",
        policyRef: outcome.policyRef,
        premiumCents: outcome.premiumCents,
        coveredFrom: outcome.coveredFrom,
        coveredTo: outcome.coveredTo,
      });
      if (compareDates(outcome.coveredFrom, occ.periodStart) > 0) {
        const nights = diffDays(occ.periodStart, outcome.coveredFrom);
        await safeSend(deps.notifier, {
          kind: "alert",
          to: "operator",
          planId: plan.id,
          occurrenceId: occ.id,
          detail: {
            problem: "insurance_starts_late",
            message: `Insurance for ${periodText} starts ${outcome.coveredFrom}: Bonzah cannot start a policy before tomorrow (Pacific), so the first ${nights} night(s) are not insured`,
          },
        });
      }
      return { ...base, outcome: "insured", premiumCents: outcome.premiumCents, policyRef: outcome.policyRef, coveredFrom: outcome.coveredFrom, coveredTo: outcome.coveredTo };
    }
    case "not_insurable":
      return decide("not_insurable", outcome.reason);
    case "retry_later":
      if (giveUp) return decide("failed", `Bonzah did not answer in time (${outcome.reason})`);
      return { ...base, outcome: "retry_later", reason: outcome.reason };
    default:
      throw new PlanStoreError("invalid_input", `Unknown insurance outcome ${JSON.stringify(outcome)}`);
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// The stage
// ─────────────────────────────────────────────────────────────────────────────

async function renewPlan(deps: RenewalDeps, plan: PlanRow, asOf: string, result: RenewalStageResult): Promise<void> {
  const today = localDateInZone(asOf, plan.timezone);
  let occs = await deps.store.listOccurrences(plan.id);
  let pricing: RenewalPricingInputs | null = null;
  const pricingFor = async () => (pricing ??= await deps.store.renewalPricing(plan.rentalId));

  // 2. APPEND — a renewal plan's next period, once its last one is settled.
  if (plan.extendsRental && plan.renewal) {
    const live = occs.filter(isLive).sort((a, b) => a.seq - b.seq);
    const last = live[live.length - 1];
    if (!last || SETTLED.has(last.status)) {
      const p = await pricingFor();
      const start = renewalChainStart(p.rentalEnd, live);
      if (start) {
        const draft = nextRenewalDraft(start, plan.renewal, p);
        const r = await deps.store.appendRenewalPeriod(plan.id, draft, null);
        if (r.appended) {
          result.appended.push({ planId: plan.id, occurrenceId: r.occurrenceId, periodStart: draft.periodStart, periodEnd: draft.periodEnd });
          occs = await deps.store.listOccurrences(plan.id);
        }
      }
    }
  }

  // 3. POST — untouched, unposted periods within the lead of their due date.
  const coverage = plan.renewal ? normalizeCoverage(plan.renewal.insurance) : null;
  for (const o of occs) {
    if (!isLive(o) || o.extensionId || !UNTOUCHED.has(o.status) || o.attemptNo !== 0) continue;
    if (compareDates(addDays(o.dueDate, -RENEWAL_POST_LEAD_DAYS), today) > 0) continue;
    try {
      const posted = await postPeriod(deps, plan, o, await pricingFor(), { coverage, giveDaysNow: false, actorId: null, automatic: true });
      if (posted.posted) {
        const fresh = await deps.store.getOccurrence(o.id);
        result.posted.push({ planId: plan.id, occurrenceId: o.id, extensionId: posted.extensionId, totalCents: fresh?.amountCents ?? o.amountCents });
      }
    } catch (e) {
      result.errors.push({ planId: plan.id, occurrenceId: o.id, message: message(e) });
    }
  }

  // 4. INSURE — before anything can charge the period.
  occs = await deps.store.listOccurrences(plan.id);
  for (const o of occs) {
    if (!isLive(o) || !o.extensionId || o.insuranceStatus !== "pending" || !UNTOUCHED.has(o.status)) continue;
    try {
      const giveUp = compareInstants(o.dueAt, asOf) <= 0;
      result.insurance.push(await insurePeriod(deps, plan, o, coverage, asOf, giveUp));
    } catch (e) {
      result.errors.push({ planId: plan.id, occurrenceId: o.id, message: message(e) });
    }
  }
}

/** The renewal stage of one tick. Every plan is handled in its own try/catch. */
export async function runRenewalStage(deps: RenewalDeps, asOf: string, filter: { tenantId?: string; planId?: string } = {}): Promise<RenewalStageResult> {
  const result: RenewalStageResult = { reconciled: [], appended: [], posted: [], insurance: [], errors: [] };
  // 1. RECONCILE
  try {
    result.reconciled = await deps.store.reconcileRenewals(filter);
  } catch (e) {
    result.errors.push({ message: `reconcile: ${message(e)}` });
  }
  let plans: PlanRow[] = [];
  try {
    plans = await deps.store.listRenewalPlans(filter);
  } catch (e) {
    result.errors.push({ message: `list: ${message(e)}` });
    return result;
  }
  for (const plan of plans) {
    try {
      await renewPlan(deps, plan, asOf, result);
    } catch (e) {
      result.errors.push({ planId: plan.id, message: message(e) });
      if (e instanceof Error && e.name === "PlanRuleError") {
        // Nothing to renew for (a $0 rate): tell a person, once per plan and problem (the notifier dedupes).
        await safeSend(deps.notifier, { kind: "alert", to: "operator", planId: plan.id, detail: { problem: "renewal_cannot_be_priced", message: message(e) } });
      }
    }
  }
  return result;
}

