/**
 * Payment plans — RENEWALS: open-ended plans that extend the rental (Wave 3,
 * spec §4 "the green line"; roadmap assumptions A3, A4, A5).
 *
 * One renewal period = one existing-shaped extension (a rental_extensions row
 * + Extension* ledger charges), priced exactly as auto-extend prices a period
 * (renewal-pricing.ts), posted by pp_post_renewal_period and collected by the
 * ordinary claim / charge / link / manual path. When the period is PAID the
 * live finalize_rental_extension moves the rental's end date inside
 * pp_record_success (A3). See supabase/migrations/20260926120200_open_ended_plans.sql.
 *
 * The engine's renewal stage (runRenewalStage) runs in every tick, after
 * recovery and BEFORE reminders — so a reminder already quotes a period's
 * final price, insurance included — in this order, per plan:
 *   1. RECONCILE: a posted period whose charges were settled outside the plan
 *      (credit, an operator's payment on the rental) is paid; its end date moves.
 *   2. APPEND: a renewal plan whose last period is settled gets the NEXT period
 *      (horizon: the next period only) — never two open periods ahead, so an
 *      unpaid period blocks the next one, as auto-extend's parked week does.
 *   3. POST: a period within RENEWAL_POST_LEAD_DAYS of its due date is posted.
 *      Posting ahead is what lets its insurance start on the period's first
 *      night: Bonzah cannot start a policy before tomorrow (Pacific).
 *   4. INSURE (A4): a posted period whose cover is still undecided is insured
 *      BEFORE it can be charged (pp_claim refuses it until then). Bought →
 *      the premium joins the period. Bonzah cannot cover it → NO premium and
 *      an operator alert. A transient failure retries on later ticks until the
 *      period falls due, then gives up the same way — never a premium without
 *      a policy.
 * Then the tick's normal due work charges the period.
 *
 * The operator's Extend (extendPlan) posts N periods now — "give the days now"
 * (the end date moves at once) or "when paid" (A3) — and records whether an
 * extension agreement goes out (A5; the portal sends it through /api/esign).
 *
 * Runtime-agnostic, like every file in this directory: relative sibling
 * imports only; no Deno.*, process.*, window.*.
 *
 * Canonical copy: supabase/functions/_shared/payment-plans/. The portal copy is
 * generated by scripts/sync-payment-plans.mjs — edit here, then sync.
 */

