export interface ExtendInput {
  planId: string;
  /** 1..MAX_EXTEND_PERIODS. */
  periods: number;
  /** A3: true → the rental's end date moves now; false → when each period is paid. */
  giveDaysNow: boolean;
  /** A5: the operator's answer; recorded here, sent by the portal (/api/esign 'extension'). */
  sendAgreement: boolean;
  /** Cover to buy for these periods; undefined = the plan's own (renewal plans), null = none. */
  insurance?: RenewalCoverage | null;
  /** A plan that does not renew has no period of its own: say it here (default one week). */
  periodUnit?: RenewalPeriodUnit;
  periodCount?: number;
  actorId?: string | null;
  asOf: string;
}

export interface ExtendedPeriod {
  occurrenceId: string;
  extensionId: string;
  periodStart: ISODate;
  periodEnd: ISODate;
  amountCents: number;
  insurance: InsuranceResult;
}

export interface ExtendResult {
  extensionIds: string[];
  occurrenceIds: string[];
  periods: ExtendedPeriod[];
  /** rentals.end_date after the Extend. */
  endDate: ISODate | null;
}

/**
 * Extend the rental on its live plan by N periods, now. Each period is posted
 * (an extension + its charges) and due TODAY on the plan's method — the next
 * cron run collects it, or the operator's Retry does at once. A renewal
 * plan's own next period, if it is not posted yet, is the FIRST of the N (its
 * due date is brought forward to today), so the chain never skips a period.
 * Insurance is bought now, once (the operator is waiting): if Bonzah cannot
 * cover a period, it carries no premium and the result says why.
 */
export async function extendPlan(deps: RenewalDeps, input: ExtendInput): Promise<ExtendResult> {
  if (!Number.isInteger(input.periods) || input.periods < 1 || input.periods > MAX_EXTEND_PERIODS) {
    throw new PlanStoreError("invalid_input", `Extend by 1 to ${MAX_EXTEND_PERIODS} periods`);
  }
  const clocked = deps.store as { setNow?: (asOf: string) => void };
  if (typeof clocked.setNow === "function") clocked.setNow(new Date(input.asOf).toISOString());
  const plan = await deps.store.getPlan(input.planId);
  if (!plan) throw new PlanStoreError("not_found", `Plan ${input.planId} not found`);
  if (plan.status !== "active") throw new PlanStoreError("refused", `The plan is ${plan.status}; resume it before extending`);

  const renewal: Pick<PlanRenewal, "periodUnit" | "periodCount"> = plan.renewal
    ? { periodUnit: plan.renewal.periodUnit, periodCount: plan.renewal.periodCount }
    : { periodUnit: input.periodUnit ?? "week", periodCount: input.periodCount ?? 1 };
  if (!["day", "week", "month"].includes(renewal.periodUnit) || !Number.isInteger(renewal.periodCount) || renewal.periodCount < 1 || renewal.periodCount > 52) {
    throw new PlanStoreError("invalid_input", "A period is 1–52 days, weeks or months");
  }
  const coverage = normalizeCoverage(input.insurance === undefined ? plan.renewal?.insurance ?? null : input.insurance);
  const actorId = input.actorId ?? null;
  const today = localDateInZone(input.asOf, plan.timezone);
  const pricing = await deps.store.renewalPricing(plan.rentalId);
  renewalBreakdownCents(pricing); // refuse a $0 period before writing anything

  const out: ExtendResult = { extensionIds: [], occurrenceIds: [], periods: [], endDate: null };
  const initial = await deps.store.listOccurrences(plan.id);
  const pending = initial.filter((o) => isLive(o) && !o.extensionId && UNTOUCHED.has(o.status) && o.attemptNo === 0).sort((a, b) => a.seq - b.seq);

  for (let i = 0; i < input.periods; i++) {
    let occ: OccurrenceRow | null;
    if (i < pending.length) {
      occ = pending[i];
      if (compareDates(occ.dueDate, today) > 0) await deps.store.moveOccurrence(occ.id, today, actorId);
    } else {
      const start = renewalChainStart(pricing.rentalEnd, await deps.store.listOccurrences(plan.id));
      if (!start) throw new PlanStoreError("refused", "This rental has no end date to extend from");
      const draft = nextRenewalDraft(start, renewal, pricing, today);
      const appended = await deps.store.appendRenewalPeriod(plan.id, draft, actorId);
      occ = await deps.store.getOccurrence(appended.occurrenceId);
    }
    if (!occ) throw new PlanStoreError("not_found", "The new period vanished");
    const posted = await postPeriod(deps, plan, occ, pricing, { coverage, giveDaysNow: input.giveDaysNow, actorId, automatic: false });
    let insurance: InsuranceResult = { occurrenceId: occ.id, outcome: "none" };
    let fresh = await deps.store.getOccurrence(occ.id);
    if (fresh && fresh.insuranceStatus === "pending") {
      insurance = await insurePeriod(deps, plan, fresh, coverage, input.asOf, true);
      fresh = await deps.store.getOccurrence(occ.id);
    }
    out.extensionIds.push(posted.extensionId);
    out.occurrenceIds.push(occ.id);
    out.periods.push({
      occurrenceId: occ.id,
      extensionId: posted.extensionId,
      periodStart: occ.periodStart as ISODate,
      periodEnd: occ.periodEnd as ISODate,
      amountCents: fresh?.amountCents ?? occ.amountCents,
      insurance,
    });
  }

  // A5: the operator's answer, on the record whichever way it went.
  await deps.store.recordEvent({
    planId: plan.id,
    occurrenceId: out.occurrenceIds[0],
    kind: "agreement_choice",
    dedupeKey: `agreement_choice:extend:${out.occurrenceIds[0]}`,
    actorId,
    detail: { sendAgreement: !!input.sendAgreement, automatic: false, giveDaysNow: !!input.giveDaysNow, extensionIds: out.extensionIds, occurrenceIds: out.occurrenceIds },
  });
  out.endDate = (await deps.store.renewalPricing(plan.rentalId)).rentalEnd;
  return out;
}
