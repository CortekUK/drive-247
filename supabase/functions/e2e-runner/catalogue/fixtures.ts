/**
 * A weekly rental that started 7 days ago and ends today, with auto-extension
 * ON. The first renewal is not yet due (next charge in 1 hour), so nothing
 * happens until the runner moves the clock.
 */
export function autoExtendWeekly(chargeMode: "auto_charge" | "pay_link"): FixtureSpec {
  return {
    shape: "auto_extend",
    periodType: "Weekly",
    // $350.00 per week, the stated auto-extend week rate.
    periodRate: { cents: 35000, math: "350.00 = 350.00", why: "the stated week rate" },
    startOffsetDays: -7,
    lengthDays: 7,
    charges: [
      // 1 week × $350.00 = $350.00, due on the start day (7 days ago).
      { category: "Rental", amount: { cents: 35000, math: "1 × 350.00 = 350.00" }, dueOffsetDays: 0 },
    ],
    card: "visa",
    autoExtend: { chargeMode, unit: "Weekly", intervalCount: 1, maxPeriods: null, firstChargeInHours: 1 },
  };
}

