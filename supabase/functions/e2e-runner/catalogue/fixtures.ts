/**
 * The stated fixture rates, and the fixture rentals built from them.
 *
 * EVERY expected money value in this catalogue comes from the rates below,
 * by hand, with the arithmetic written next to it. If a rate changes here,
 * every derivation that uses it must be redone by a person — the L1 suite
 * re-evaluates each `math` string, so a stale one fails loudly.
 *
 *   BOOKING DAY RATE        $100.00 / day      (Daily rental, 3 days)
 *   EXTENSION DAY RATE      $100.00 / day      (the same daily rate, 2 extra days)
 *   AUTO-EXTEND WEEK RATE   $350.00 / week     (Weekly rental, renews weekly)
 *   PAYG DAY RATE           $40.00 / day       (pay-as-you-go, accrues daily)
 *   INSTALLMENT             3 × $200.00        ($600.00 booking)
 *   PAYMENT PLAN            $600.00 split 3 ways, weekly
 *   PREPAID CREDIT          $350.00            (one week of auto-extend)
 *
 *   Every fixture starts on the visa card (or none): sandbox-fixture-setup
 *   places a real TEST deposit hold on the card it mints, and a card that
 *   declines or demands authentication off-session would fail that hold. A
 *   scenario that needs a bad card swaps it in with a `swap_card` step.
 *
 *   Tax and service fee: OFF. The tenant must say so (`tax_off`,
 *   `service_fee_off`) wherever a job prices from the tenant's settings —
 *   the runner checks before it writes anything, and refuses rather than
 *   compare against a number it would have to recompute.
 *
 * Canonical copy: tests/e2e/scenarios/. The edge-function copy
 * (supabase/functions/e2e-runner/catalogue/) is generated by
 * `node tests/e2e/sync-catalogue.mjs` — edit here, then sync.
 */

