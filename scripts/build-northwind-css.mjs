#!/usr/bin/env node
/**
 * Compile the new Northwind booking design's stylesheet.
 *
 *   node scripts/build-northwind-css.mjs
 *
 * The design (apps/booking/src/northwind-site, routes in
 * apps/booking/src/app/(northwind)) is written for Tailwind 4. The booking app
 * builds Tailwind 3 for every other tenant, and one Next app has one PostCSS
 * pipeline — so this stylesheet is compiled here, ahead of time, and committed:
 *
 *   source  apps/booking/src/northwind-site/styles/site.css
 *   output  apps/booking/public/nw-assets/site.<hash>.css
 *           apps/booking/src/northwind-site/site-css.ts   (the file's URL)
 *
 * The (northwind) root layout links the output; nothing else loads it, so no
 * other tenant's page ever receives these styles.
 *
 * RE-RUN after changing any class name in the design's files. The generated
 * file only contains the classes it found.
 *
 * Toolchain: the Tailwind 4 already installed for v2/apps/web (where the design
 * was built). Nothing here is installed into the booking app.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const BOOKING = path.join(ROOT, 'apps/booking');
const SOURCE = path.join(BOOKING, 'src/northwind-site/styles/site.css');
const OUT_DIR = path.join(BOOKING, 'public/nw-assets');
const URL_MODULE = path.join(BOOKING, 'src/northwind-site/site-css.ts');
const TOOLCHAIN_DIR = path.join(ROOT, 'v2/apps/web');

const requireTool = createRequire(path.join(TOOLCHAIN_DIR, 'package.json'));
let postcss, tailwind;
try {
  postcss = requireTool('postcss');
  tailwind = requireTool('@tailwindcss/postcss');
} catch {
  console.error('Tailwind 4 is not installed. Run:  npm --prefix v2/apps/web install');
  process.exit(1);
}

const slash = (p) => p.split(path.sep).join('/');
const tailwindIndex = slash(requireTool.resolve('tailwindcss/index.css'));
const twAnimate = slash(path.join(TOOLCHAIN_DIR, 'node_modules/tw-animate-css/dist/tw-animate.css'));

// The source imports its packages by name, as it did in v2/apps/web. Resolved
// from the booking app those names would find the booking app's Tailwind 3, so
// they are pointed at the Tailwind 4 files explicitly.
let css = fs.readFileSync(SOURCE, 'utf8');
for (const [spec, file] of [['tailwindcss', tailwindIndex], ['tw-animate-css', twAnimate]]) {
  const re = new RegExp(`@import\\s+["']${spec}["']\\s*;`);
  if (!re.test(css)) throw new Error(`site.css no longer imports "${spec}" — update this script`);
  css = css.replace(re, `@import "${file}";`);
}
// Class names come from the design's code and its routes, nothing else.
css = `@source "../../app/(northwind)";\n${css}`;

const result = await postcss([
  tailwind({ base: path.join(BOOKING, 'src/northwind-site'), optimize: { minify: true } }),
]).process(css, { from: SOURCE });

const hash = crypto.createHash('sha256').update(result.css).digest('hex').slice(0, 10);
const fileName = `site.${hash}.css`;

fs.mkdirSync(OUT_DIR, { recursive: true });
for (const old of fs.readdirSync(OUT_DIR)) {
  if (/^site\.[0-9a-f]+\.css$/.test(old) && old !== fileName) fs.unlinkSync(path.join(OUT_DIR, old));
}
fs.writeFileSync(path.join(OUT_DIR, fileName), result.css);
fs.writeFileSync(
  URL_MODULE,
  `// Generated by scripts/build-northwind-css.mjs — do not edit. Re-run it instead.\nexport const NORTHWIND_SITE_CSS = "/nw-assets/${fileName}";\n`,
);

console.log(`apps/booking/public/nw-assets/${fileName}  ${(result.css.length / 1024).toFixed(1)} KB`);
