import { chromium } from 'playwright';
const url = process.argv[2];
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true });
const p = await b.newPage();
const api = [];
p.on('response', async r => { if (/checkout|session/i.test(r.url()) && r.url().includes('stripe')) api.push(r.url()); });
await p.goto(url, { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3000);
const txt = await p.evaluate(() => document.body.innerText);
console.log("=== VISIBLE TEXT ===");
console.log(txt.slice(0, 1500));
const anchors = await p.evaluate(() => Array.from(document.querySelectorAll('a')).map(a=>a.href).filter(Boolean));
console.log("=== ANCHORS ==="); console.log([...new Set(anchors)].join('\n'));
console.log("=== FINAL URL ==="); console.log(p.url());
await b.close();
